import io

p = 'tests/integration/vfs_edge_tests.cpp'
d = open(p, 'rb').read().decode('utf-8')
lines = d.split('\n')
start = 180  # 0-based index of line 181
end = 193    # 0-based index of line 194 (the [[nodiscard]] line)
old = '\n'.join(lines[start:end])
new = """// ДОСЫЛКА ПЕРЕД ЗАКРЫТИЕМ (D-78) — обязательная часть записи, а не украшение.
// Файловая система публикует метаданные свежезаписанного файла не сразу:
// GetCompressedFileSizeW открывает файл заново и читает ОПУБЛИКОВАННОЕ
// значение, а NTFS откладывает запись метаданных до ближайшего сброса. Без
// досылки проверка «allocated >= logical» зависит от того, успел ли кэш
// сброситься: из 14 прогонов набора на одних и тех же бинарниках один давал
// allocated 0 при logical 5000 (D-78, docs/defects.md §3.18.3), то есть сам
// критерий приёмки был монеткой. Досылка делает состояние файла наблюдаемым
// сразу после close() и убирает окно, в котором значение ещё не опубликовано.
// Само округление до кластера досылка НЕ публикует — см. комментарий у
// measurePublishedAllocated: там же измерено, что по пути отдаётся ровно EOF.
// Отдельно от этого writeFile честно отдаёт ERROR_DISK_FULL: на томе без
// свободного места (в этой задаче измерен C: с нулём свободных байт, из-за
// чего фикстуры не создавались и проверка уходила в видимый пропуск) файл не
// создаётся — это тоже должно быть видно, а не «красный на пустом месте»."""
assert old.startswith('// Пока файл не досылан'), old[:60]
d = d.replace(old, new)
open(p, 'wb').write(d.encode('utf-8'))
print('replaced ok')
