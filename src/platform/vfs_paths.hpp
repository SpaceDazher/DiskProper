// MrProper — нормализация путей и проверка принадлежности корню правила.
// Спека: §4 FR-6 (защита от «съедания» чужих данных: нормализация через
// GetFinalPathNameByHandleW, поддержка `\\?\` для путей длиннее MAX_PATH,
// пропуск reparse points, белый список защищённых каталогов, проверка попадания
// внутрь ожидаемого корня правила), §10 (риск «один неверный путь — это
// удаление пользовательских данных», митигация `GetFinalPathNameByHandleW` +
// `\\?\` + пропуск reparse), §5 (длинные пути, пробелы, не-ASCII, кириллица,
// hard links, ADS), §12 (инвариант приёмки «отсутствие изменений вне корней
// правил»).
//
// Зачем модуль именно такой. Правило задаёт корень вида
// «%LOCALAPPDATA%\Microsoft\Edge\User Data», движок обходит дерево и получает
// миллион путей, а правило
// «не удалять вне своего корня» обязано быть ДОКАЗАНЫМ, а не предположенным.
// Текстовое сравнение строк для этого не годится, и не из-за кириллицы:
//
//   * «C:\Users\Ev» как корень не должен влезать «C:\Users\Evil\x» — префикс
//     совпадает, каталог другой;
//   * «C:\PROGRA~1\X» и «C:\Program Files\X» — один каталог, разный текст;
//   * junction «C:\Users\me\Downloads -> C:\Windows\WinSxS» даёт путь внутри
//     корня правила, который физически лежит снаружи;
//   * «C:\Users\..\Windows» текстуально внутри «C:\Users», а физически это
//     «C:\Windows».
//
// Единственный ответ, который отличает «это тот же каталог» от «это другой
// каталог», — спросить у файловой системы: открыть объект и получить его
// настоящее имя. Это и делает GetFinalPathNameByHandleW: снимает короткие имена
// 8.3, разворачивает symlink и junction, приводит том к букве диска. Дальше
// остаётся только честное сравнение двух нормализованных строк.
//
// Граница модуля — решение «можно ли трогать этот путь», и ничего кроме.
//
//   * обход дерева (FindFirstFileW, счётчики, рекурсия, обход reparse) —
//     соседние модули vfs_walk/vfs_size;
//   * удаление и перенос — vfs_delete/vfs_trash: этот модуль ничего не
//     удаляет, только выдаёт вердикт, который те вызывают ДО операции;
//   * Restart Manager, занятые файлы (FR-6) — отдельный модуль;
//   * разбор локаторов правила (%, **, ?) — core::rules: сюда приходит уже
//     развёрнутый, готовый путь.
//
// Кодировки. Наружу модуль говорит в UTF-8 (так пути хранит модель, §6.3 и
// core::model::CleanupCandidate::path), внутрь обращается к WinAPI в UTF-16
// (SPEC §6.3). Преобразованиями владеет win_error.hpp, своими — этот файл не
// пользуется: две реализации toUtf8 в проекте — это два места, где однажды
// разойдутся.
//
// Устойчивость. Ни одна функция не бросает исключений (§4 FR-1 «устойчивость»
// распространяется и на слой Win32, §6.4 — отказ в горячем цикле это флаг, а не
// исключение). Любой отказ виден в lastError и в вердикте; «не смогли решить»
// и «решили, что нельзя» — разные вердикты, и оба означают «не удалять».
//
// Файл не включает windows.h — намеренно, как storage_query.hpp и
// devices.hpp: объявления используют только переносимые типы, поэтому заголовок
// может включить и слой без Win32, а единица трансляции, которой windows.h
// нужен по существу, добавляет его сама. Так граница слоёв (ADR-004) не
// размывается лишним заголовком.
#pragma once

#include <cstdint>
#include <string>
#include <string_view>
#include <vector>

namespace mrproper::platform::vfs_paths {

// ---------------------------------------------------------------------------
// Форма пути
// ---------------------------------------------------------------------------

// Путь файловой системы, от которого можно что-то делать: «C:\…»,
// «\\server\share\…» и их расширенные формы. Всё остальное — не путь ФС:
// относительный («Temp\x»), привязанный к диску («C:x» — текущий каталог
// диска C), устройство («\\.\PhysicalDrive0», «\\.\PIPE\…») и пустота.
//
// Отдельная функция, потому что её ответ — половина безопасности: движок
// delete/trash обязан отвергнуть привязанный к диску путь ДО нормализации, иначе
// «C:x» превратится в «C:\текущий-каталог» и удалит не то.
[[nodiscard]] bool isRootedFileSystemPath(std::string_view pathUtf8) noexcept;

// Именованный поток (ADS, §5: «ADS не трогаем» — поведение определено явно):
// в «C:\a.txt:поток» или «\\?\C:\a.txt:поток» всё после второго двоеточия —
// поток, а не имя файла. Хвост с двоеточием в префиксе тома («C:»,
// «\\?\C:») потоком не считается.
[[nodiscard]] bool hasStreamSuffix(std::string_view pathUtf8) noexcept;

// Компонент «.» или «..» где-либо в пути. Такой путь отвергается на входе, и
// это не перестраховка: для формы `\\?\` разбор точек отдаётся ядру
// («\\?\» выключает автоматическое разворачивание пути), и разбирать «..» на
// своей стороне значит разбирать его не так, как это сделает файловая система.
[[nodiscard]] bool hasDotSegment(std::string_view pathUtf8) noexcept;

// ---------------------------------------------------------------------------
// \\?\ — пути длиннее MAX_PATH
// ---------------------------------------------------------------------------

// Расширенная форма пути: «C:\Users\x» → «\\?\C:\Users\x»,
// «\\server\share\x» → «\\?\UNC\server\share\x». Ровно то, о чём FR-6: без
// префикса путь длиннее MAX_PATH не откроется, сколько бы манифест ни был
// longPathAware.
//
// Уже расширенные пути и пути пространства устройств возвращаются БЕЗ
// изменений: префикс к «\\.\PhysicalDrive0» или к «\\?\C:\x» — не просто
// лишнее, это другая цель в диспетчере объектов. Пустая строка на выходе —
// отказ: путь не приведён (относительный, привязанный к диску) либо не
// разбирается как UTF-8.
[[nodiscard]] std::string toExtendedPath(std::string_view pathUtf8) noexcept;

// ---------------------------------------------------------------------------
// Reparse points
// ---------------------------------------------------------------------------

// Является ли сам объект точкой перехода (symlink, junction, mount point).
// FR-6: «пропуск reparse points (symlink/junction) — защита от петель и выхода за
// пределы пути». Проверяется атрибут исходного пути: у самой цели признака
// обычно нет, признак у ссылки. lastError заполняется только при отказе
// (файла нет, нет прав) — истина означает «решать нельзя».
[[nodiscard]] bool isReparsePoint(std::string_view pathUtf8, std::uint32_t& lastError) noexcept;

// ---------------------------------------------------------------------------
// Нормализация
// ---------------------------------------------------------------------------

// Настоящее имя объекта по GetFinalPathNameByHandleW: короткие имена 8.3
// развёрнуты, symlink/junction пройден, том приведён к букве диска либо к
// «\\?\Volume{GUID}\…» (тома без буквы иначе не представить).
struct Resolution {
    // Нормализованный путь, UTF-8, в форме GetFinalPathNameByHandleW. Пусто,
    // если resolved == false.
    std::string path;
    // Код Windows последнего отказа. 0 при успехе; «решение движка» (например,
    // вердикт reparse) кодом не сопровождается и остаётся нулём.
    std::uint32_t lastError{0};
    // Имя получено.
    bool resolved{false};
    // Имя получено нормализацией (FILE_NAME_NORMALIZED) И атрибуты исходного
    // пути прочитаны, то есть доказуемо одно и то же каталог, даже если путь
    // шёл через 8.3 или reparse. При strong == false доказательства нет: имя
    // получено в том виде, в каком открыли (FILE_NAME_OPENED), либо атрибуты
    // исходного пути не прочитались. Проверка принадлежности корню на таком
    // результате вердикт выносить не должна.
    bool strong{false};
    // Объект сам является точкой перехода.
    bool reparsePoint{false};
    // Каталог (не файл).
    bool directory{false};

    [[nodiscard]] bool ok() const noexcept { return resolved; }
};

// Нормализация одного пути. Права — FILE_READ_ATTRIBUTES плюс
// FILE_FLAG_BACKUP_SEMANTICS, то есть минимум, который позволяет и спросить
// имя каталога, и не требовать повышения прав (SPEC §5: приложение стартует
// без повышения). Ни FILE_SHARE_DELETE, ни право удаления тут не нужны: решает
// не модуль, а вызывающий — после того как получит вердикт.
[[nodiscard]] Resolution resolve(std::string_view pathUtf8) noexcept;

// ---------------------------------------------------------------------------
// Принадлежность корню
// ---------------------------------------------------------------------------

// Лежит ли путь внутри корня. Сравнение покомпонентное и регистронезависимое
// (CompareStringOrdinal, а не свёртка регистра: в турецкой локали «I» и «ı» —
// разные буквы, и «C:\ınner» не должен совпасть с «C:\INNER»). Граница
// компонента проверяется явно, поэтому «C:\Users\Ev» не влезает в
// «C:\Users\Evil». Оба аргумента приводятся к расширенной форме и
// case-независимо сравниваются в том виде, который вернул бы файловый систему.
//
// Сравнение ТЕКСТА, а не объектов: сюда передают уже нормализованные пути из
// resolve(). Для сырого пути правила «C:\PROGRA~1\X» против корня
// «C:\Program Files» ответ будет «нет» — ложный запрет, а не ложное
// разрешение. Порядок вызова (нормализовать, потом сравнить) задан
// checkRuleRoot и prepareRoot.
//
// Завершающие разделители с обеих сторон снимаются, поэтому «C:\Users» и
// «C:\Users\» — один корень, а «C:\» и «C:» не путаются между собой и с
// «C:\Users».
[[nodiscard]] bool isInsideRoot(std::string_view pathUtf8, std::string_view rootUtf8) noexcept;

// ---------------------------------------------------------------------------
// Белый список защищённых каталогов
// ---------------------------------------------------------------------------

// Корни, которые движок не трогает никогда (FR-6: «белый список защищённых
// каталогов (Windows, Program Files, System Volume Information) — правило
// запрета на уровне движка»). Список собирается из переменных окружения
// (SystemRoot, ProgramFiles, ProgramFiles(x86), ProgramW6432) с запасом в виде
// литералов «C:\Windows», «C:\Program Files», «C:\Program Files (x86)»: пути
// в наборе правил записаны литералами (§9.2), и движок не должен вести себя
// иначе при развёрнутой и не развёрнутой строке. Окружение читается один раз за
// процесс — оно не меняется, а проверка идёт на каждом файле.
//
// Второй защищённый случай — «System Volume Information»: имя задаёт каталог,
// а защищает его положение прямым потомком корня тома, поэтому проверяется не
// имя, а имя вместе с местом. «C:\Backup\System Volume Information» обычным
// пользовательским каталогом остаётся.
[[nodiscard]] std::vector<std::string> protectedRootsUtf8();

// Путь внутри защищённого каталога (в любом из защищённых корней либо сам
// защищённый каталог). Корни сравниваются покомпонентно и регистронезависимо,
// поэтому «C:\Windows.old» защищённым не считается — это другой каталог, хоть
// и с похожим именем, а «C:\Windows» внутри «C:\Windows.old» — да.
[[nodiscard]] bool isProtectedPath(std::string_view pathUtf8) noexcept;

// ---------------------------------------------------------------------------
// Сводная проверка для движка
// ---------------------------------------------------------------------------

// Решение движка по одному пути. Порядок выверен от «самого безобидного» к
// «самому опасному»: сначала форма пути, потом нормализация, потом reparse,
// потом граница корня, потом белый список. Порядок не меняет безопасности
// (любой не-«inside» означает «не трогать»), но меняет текст в отчёте, а текст
// в отчёте — это то, по которому человек разбирается, почему файл уцелел.
enum class Verdict {
    Inside,        // путь внутри корня правила и ни одно правило не нарушено
    OutsideRoot,   // нормализованный путь ушёл за пределы корня правила
    ReparsePoint,  // объект — symlink/junction: FR-6 требует его пропустить
    ProtectedPath, // защищённый системный каталог (FR-6, белый список)
    Unresolvable,  // решить нельзя: отказ ФС, нет прав, неприемлемая форма пути
};

// Короткое имя вердикта для журнала и отчёта.
[[nodiscard]] const char* verdictName(Verdict verdict) noexcept;

// Результат проверки пути. lastError заполнен кодом Windows, когда решение
// приняла файловая система; решение самого движка (reparse, форма пути, граница
// корня) код сопровождает только там, где код и правда есть.
struct Guard {
    Verdict verdict{Verdict::Unresolvable};
    // Нормализованный путь, если его удалось получить: без него в отчёте не
    // на что посмотреть. Пусто, когда нормализация не сошлась.
    std::string normalized;
    std::uint32_t lastError{0};

    // Единственный вердикт, из которого движок имеет право делать операцию
    // без дополнительного подтверждения. ProtectedPath — осознанно не «да»:
    // по FR-9 смена safety-уровня требует двойного подтверждения, и решать,
    // можно ли трогать C:\Windows, должен человек, а не этот модуль.
    [[nodiscard]] bool allowed() const noexcept { return verdict == Verdict::Inside; }
};

// Корень правила, подготовленный один раз на правило, а не на файл. На прогоне
// по 500 тыс. файлов (SPEC §11 п.6) повторное открытие каталога на каждый файл
// — это миллион лишних CreateFileW, поэтому нормализация корня вынесена из
// проверки пути.
struct RootGuard {
    // Нормализованный корень в форме GetFinalPathNameByHandleW.
    std::string root;
    std::uint32_t lastError{0};
    // Корень разрешён и пригоден как граница.
    bool resolved{false};
    // Корень отвергнут: не путь ФС, содержит «.»/«..» или ADS, не открылся, сам
    // является точкой перехода. При rejected любой путь даёт Unresolvable.
    bool rejected{false};
};

// Подготовка корня правила. Отвергает корень, который сам является точкой
// перехода: правило, уводящее обход за пределы своего каталога, — это не
// правило, а закладка на удаление мимо корня.
[[nodiscard]] RootGuard prepareRoot(std::string_view rootUtf8) noexcept;

// Проверка пути против подготовленного корня. Порядок:
//
//   1. форма пути (не путь ФС / «.»-компонент / ADS) → Unresolvable;
//   2. нормализация: нет имени, или имя не нормализовано (strong == false) →
//      Unresolvable. Второе — сознательный отказ от решения: доказательством
//      «путь внутри корня» служит только нормализованное имя, а имя «как
//      открыли» не отличает «C:\PROGRA~1\X» от «C:\Program Files\X»;
//   3. объект — reparse point → ReparsePoint (FR-6, пропуск);
//   4. путь вне корня → OutsideRoot;
//   5. защищённый каталог → ProtectedPath;
//   6. иначе Inside.
//
// Каждый не-Inside попадает в журнал с путём и кодом Windows (SPEC §12: «все
// ошибки в логе с путём и HRESULT»). Успех не пишется: на проходе по сотням
// тысяч файлов это был бы самый горячий вызов журнала в приложении, а
// разрешённый путь интереса для разбора не имеет.
[[nodiscard]] Guard checkRuleRoot(std::string_view pathUtf8, const RootGuard& root) noexcept;

// То же, но корень готовится на месте. Удобно для единичных проверок и для
// тестов; в цикле обхода используется перегрузка с RootGuard.
[[nodiscard]] Guard checkRuleRoot(std::string_view pathUtf8, std::string_view rootUtf8) noexcept;

}  // namespace mrproper::platform::vfs_paths
