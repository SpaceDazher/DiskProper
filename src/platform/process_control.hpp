// ---------------------------------------------------------------------------
// Значения по умолчанию (FR-6)
// ---------------------------------------------------------------------------

// «повтор с backoff 3×» (FR-6): три попытки RmShutdown, то есть две паузы.
inline constexpr std::uint32_t kDefaultShutdownAttempts = 3;

// Пауза между попытками растёт как base·2^n (n — номер повтора) и упирается в
// потолок. Первая пауза заметно длиннее, чем при удалении файла: после WM_CLOSE
// приложение ещё закрывает окна и сбрасывает на диск, и повтор через 50 мс
// приходит в тот же незакрытый процесс.
inline constexpr std::chrono::milliseconds kDefaultShutdownBackoff{250};
inline constexpr std::chrono::milliseconds kDefaultMaxShutdownBackoff{2000};

// Сколько ждём фактического выхода процессов после того, как RM сообщил «закрыто».
// Ответ RM — это команда, а не факт: приложение могло зависнуть на своём
// обработчике сохранения. Файл всё ещё может быть занят, поэтому движок должен
// знать, завершился ли процесс на самом деле. Ноль — не ждать вовсе и положиться
// на ответ RM (нужно для тестов и для пакетной чистки, где важна скорость).
inline constexpr std::chrono::milliseconds kDefaultExitWait{10000};

// Срез ожидания: отмена не должна ждать конца паузы или конца exitWait.
inline constexpr std::chrono::milliseconds kWaitSlice{25};

// Сколько попыток RmGetList делается, прежде чем признать сессию RM нечитаемой.
// RmGetList может вернуть ERROR_MORE_DATA, если список успел измениться между
// двумя вызовами, — это единственный ожидаемый повтор.
inline constexpr std::uint32_t kSessionListAttempts = 3;

// Сколько попыток CreateToolhelp32Snapshot. Снимок процесса может вернуть
// ERROR_BAD_LENGTH при высокой нагрузке — это известное поведение Toolhelp32,
// и оно лечится повтором, а не отказом.
inline constexpr std::uint32_t kSnapshotAttempts = 3;

// Свыше этого числа процессов в предпросмотре диалог обязан быть
// прокручиваемым: модуль пишет предупреждение в лог, но список не режет —
// молча выбросить из подтверждения процесс, который держал файл, значит
// превратить подтверждение в обман.
inline constexpr std::size_t kLargePreviewWarning = 16;

// ---------------------------------------------------------------------------
// Процесс
// ---------------------------------------------------------------------------

// Процесс, который пользователь собирается закрыть. Имя образа хранится
// рядом с PID не для красоты: имя нужно и диалогу («закрыть Chrome?»), и
// проверке защищённого списка, и журналу. startTimeTicks — время создания
// процесса в тиках FILETIME: RM идентифицирует процесс именно парой
// (PID, время создания), и без неё переиспользованный PID указывал бы на
// чужой процесс. Ноль означает «прочитать при регистрации»; если прочитать не
// удалось, процесс в предпросмотре помечается как непроверяемый и не
// закрывается.
struct ProcessRef {
    std::uint32_t pid{};
    std::uint64_t startTimeTicks{};
    std::wstring name;  // имя образа: "chrome.exe" или "chrome" — сравнение не зависит от суффикса
};

// ---------------------------------------------------------------------------
// Решения и статусы
// ---------------------------------------------------------------------------

// Решение, принятое до подтверждения: что модуль вообще готов сделать с этим
// процессом. Ни одно из решений, кроме WouldClose, не требует подтверждения —
// показывать пользователю «закроем lsass» незачем и опасно.
enum class ShutdownDecision : std::uint8_t {
    WouldClose = 0,  // процесс жив, не защищён, не мы — кандидат на закрытие
    AlreadyExited,   // процесса уже нет: закрывать нечего, чистить можно
    Protected,       // системный процесс: закрывать нельзя никогда
    Self,            // это текущий процесс MrProper
    Unknown,         // PID не существует либо время запуска прочитать не удалось
};

// Что в итоге произошло с процессом. Значения ложатся в отчёт без разбора
// (§4 FR-8, §12), поэтому их немного и каждое означает ровно одно решение.
enum class ShutdownStatus : std::uint8_t {
    NotAttempted = 0,  // решение политики: закрывать не будем (см. ShutdownDecision)
    Closed,            // процесс завершился, файлы разблокированы
    AlreadyExited,     // процесса не было уже на момент закрытия: чистить можно
    NotConfirmed,      // пользователь не подтвердил закрытие этого процесса
    Refused,           // приложение закрыться не дало (запрет на shutdown, критический процесс)
    Timeout,           // RM закрыл, но процесс не завершился за exitWait
    Cancelled,         // отмена через stop_token (§6.4)
    Failed,            // прочая ошибка, в том числе нет прав на чужой процесс
};

[[nodiscard]] const char* toString(ShutdownDecision decision) noexcept;
[[nodiscard]] const char* toString(ShutdownStatus status) noexcept;

// Процесса больше нет: файлы разблокированы, чистить можно. Сюда входит и
// AlreadyExited — процесс, который к моменту закрытия уже завершился сам, блокировки
// не держит ровно так же, как закрытый нами.
[[nodiscard]] bool isClosed(ShutdownStatus status) noexcept;

// Решение модуля или отказ пользователя: ошибки нет, но закрытия не будет.
// Именно эти статусы движок превращает в PlanAction::SkipLocked (FR-5) и в
// строку отчёта «пропущено», а не в «ошибка очистки».
[[nodiscard]] bool isSkipped(ShutdownStatus status) noexcept;

// ---------------------------------------------------------------------------
// Запись о процессе
// ---------------------------------------------------------------------------

// Одна строка предпросмотра и/или итога. Один тип на оба этапа намеренно:
// UI показывает то, что придёт в отчёт, и разбирать два разных списка ему не
// нужно.
struct ShutdownEntry {
    ProcessRef process;
    ShutdownDecision decision{ShutdownDecision::Unknown};
    ShutdownStatus status{ShutdownStatus::NotAttempted};
    std::int32_t hr{};         // HRESULT отказа: 0, если отказа не было
    std::uint32_t attempts{};  // попыток RmShutdown на этот процесс
    std::wstring detail;       // причина на человеческом языке, UTF-16 (§6.3: слой — UTF-16)

    [[nodiscard]] bool closed() const noexcept {
        return isClosed(status);
    }

    [[nodiscard]] bool approvable() const noexcept {
        return decision == ShutdownDecision::WouldClose;
    }
};

// Предпросмотр: что будет закрыто, что защищено, кого уже нет. Ни одного
// побочного эффекта — его можно показать пользователю и отменять сколько угодно.
struct ShutdownPreview {
    std::vector<ShutdownEntry> entries;

    // Что собирались чистить: контекст для заголовка диалога и для журнала.
    // Пустой путь — допустимо (закрыть по имени из правила, без привязки к
    // конкретному файлу).
    std::wstring resourcePath;

    [[nodiscard]] std::size_t approvableCount() const noexcept;
    [[nodiscard]] std::size_t protectedCount() const noexcept;
    [[nodiscard]] std::size_t alreadyExitedCount() const noexcept;

    // Нужно ли вообще что-то подтверждать: нет кандидатов — диалог не показываем.
    [[nodiscard]] bool needsConfirmation() const noexcept {
        return approvableCount() > 0;
    }

    // Список для интерфейса одной строкой: "chrome (1234), msedge (5678)".
    // Тексты кнопок и заголовка — зона UI (§7); модуль даёт только факты.
    [[nodiscard]] std::wstring describe() const;
};

// ---------------------------------------------------------------------------
// Подтверждение и параметры
// ---------------------------------------------------------------------------

// Подтверждение пользователя. Вызывается ровно один раз, до первого
// RmShutdown, и получает ровно тот список, который модуль собирается закрыть.
// Реализация — диалог UI: показывает список, спрашивает, и кладёт в approved
// то, на что пользователь нажал «закрыть» (отмеченные галочками). Второй
// аргумент заполняет вызывающий; модуль проверяет, что в approved нет
// процесса, которого не было в предпросмотре.
//
// Возврат false — отказ: закрывается ничего. Исключение из колбэка считается
// отказом (диалог упал — это не согласие).
using ShutdownConfirmation = std::function<bool(const ShutdownPreview& preview, std::vector<ProcessRef>& approved)>;

struct ShutdownOptions {
    // Обязательное поле. Пустой колбэк → NotConfirmed, ничего не закрыто.
    ShutdownConfirmation confirm{};

    // true — RmShutdown с RmForceShutdown (процесс завершается принудительно,
    // несохранённое теряется); false — приложение получает WM_CLOSE и может
    // спросить пользователя о несохранённом. По умолчанию false: §1.1 ставит
    // безопасность данных выше удобства, а «приложение спросило, сохранять ли»
    // — это ровно то поведение, за которым выбирают утилиту, а не CCleaner.
    bool force{false};

    // Повтор с backoff (FR-6: 3×). Ноль или единица — без повтора.
    std::uint32_t maxAttempts{kDefaultShutdownAttempts};

    // Пауза перед повтором; растёт вдвое, потолок — maxBackoff.
    std::chrono::milliseconds backoff{kDefaultShutdownBackoff};
    std::chrono::milliseconds maxBackoff{kDefaultMaxShutdownBackoff};

    // Ожидание фактического выхода после успешного ответа RM. Ноль — не ждать.
    std::chrono::milliseconds exitWait{kDefaultExitWait};

    // Контекст «что чистим» для диалога и журнала. View живёт в вызывающем:
    // копия делается в ShutdownPreview.
    std::wstring_view resourcePath{};
};

// ---------------------------------------------------------------------------
// Итог
// ---------------------------------------------------------------------------

struct ShutdownSummary {
    // Тот же состав, что и в предпросмотре, но со статусом и HRESULT.
    std::vector<ShutdownEntry> entries;

    std::wstring resourcePath;

    // Счётчики для прогресса и отчёта: по одному статусу на процесс.
    std::size_t closed{};
    std::size_t alreadyExited{};
    std::size_t protectedSkipped{};
    std::size_t selfSkipped{};
    std::size_t unknownSkipped{};
    std::size_t notConfirmed{};
    std::size_t refused{};
    std::size_t timedOut{};
    std::size_t cancelled{};
    std::size_t failed{};

    std::uint32_t attempts{};  // суммарно попыток RmShutdown
    std::chrono::milliseconds waited{};

    // Первый отказ в пачке: 0 — отказов не было. В лог идёт вместе с путём
    // (§12: «все ошибки в логе с путём и HRESULT»).
    std::int32_t hr{};

    bool confirmed{};  // пользователь подтвердил закрытие (хотя бы одного)

    // Ни один процесс не остался запущенным: каждая запись закончилась либо
    // закрытием, либо тем, что процесса уже не было. Статусы у записи
    // взаимоисключающие, поэтому такая сумма означает ровно одно — блокировки
    // сняты и удаление можно повторять. Приложение, которое закрыться не
    // дало (refused/timeout/failed), сюда не попадает: движок обязан отметить
    // такие кандидаты как Skip (locked) (FR-5), а не идти удалять снова.
    [[nodiscard]] bool allClosed() const noexcept {
        return !entries.empty() && closed + alreadyExited == entries.size();
    }
};

