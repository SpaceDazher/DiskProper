// Закрытие процессов по запросу пользователя: Restart Manager (RmShutdown) с
// обязательным подтверждением, защитой системных процессов, повтором с backoff
// 3× и ожиданием фактического выхода.
//
// Спека: §4 FR-6 («блокировки: определение через Restart Manager, опция “закрыть
// эти приложения” (RmShutdown) с подтверждением; повтор с backoff 3×», «ошибки не
// фатальны: собираются в отчёт, остальные операции продолжаются»), §6.2
// (`platform::procs` — «Restart Manager, список процессов, “кто держит файл”»),
// §6.4 (отмена кооперативная, `std::stop_token`), §7.2 («ничего не удаляется без
// явного действия и списка того, что будет удалено»), §5 («рантайм-повышения
// нет; повышение — один раз при старте», «ни один отказ … не роняет процесс»),
// §1.1 (приоритеты: безопасность данных → понятность объяснений → обратимость),
// §10 (митигация «удаление “живых” файлов при работающих приложениях»),
// §12 («все ошибки в логе с путём и HRESULT»).
//
// ---------------------------------------------------------------------------
// Границы модуля: что он делает и что НЕ делает намеренно
// ---------------------------------------------------------------------------
//
// 1. Только закрытие, только по подтверждению. Определение блокировок
//    (RmGetList по файлу — «кто держит файл») живёт в соседнем модуле
//    restart_manager: этот модуль берёт готовый список PID и умеет его закрыть,
//    а поимённый поиск запущенных процессов (FR-3/FR-4
//    `requiresProcessesClosed: ["msedge"]`) делает сам через Toolhelp32 — ждать
//    готовый соседний модуль нельзя, иначе очистка кэша браузера встанет в
//    зависимость от чужой задачи.
//
// 2. Подтверждение встроено в контракт, а не оставлено на волю вызывающего.
//    closeProcesses без `ShutdownOptions::confirm` не закрывает ничего и
//    возвращает NotConfirmed: «забыли показать диалог» приводит к тихому
//    отказу, а не к тихому закрытию чужих приложений. Обойти это нельзя —
//    отдельного «закрыть без спроса» в модуле просто нет.
//
// 3. Системные процессы закрыть нельзя, и это не настройка. Список защищённых
//    имён (см. isProtectedProcess) жёсткий: флага «снять запрет» не существует
//    намеренно, потому что через год его включат ради «очистить побробнее», и
//    вместо чистки кэша получится потеря сессии или система, которая не грузится.
//    Дополнительно RM сам сообщает RmCritical о процессах, которые закрывать
//    нельзя (см. реализацию) — два независимых заслона на одном и том же риске.
//
// 4. Никаких окон и никакого текста интерфейса. Диалог подтверждения
//    принадлежит UI (§7): модуль отдаёт предпросмотр (кто будет закрыт, кто
//    защищён, кого уже нет) и получает обратно подтверждённый список. Тексты
//    кнопок, заголовок окна и переводы — зона core::i18n и слоя UI, а не
//    платформы: иначе Win32-модуль потянул бы за собой локализацию.
//
// 5. Привилегий нет (§5). Нет прав на чужой процесс (другой пользователь,
//    повышенная целостность) — это Failed с настоящим HRESULT и записью в
//    лог, а не повод поднимать права из слоя. Повтор в этом случае не
//    делается: ACCESS_DENIED не проходит сам.
//
// 6. Модуль самодостаточен: не включает заголовки соседних модулей
//    src/platform (все пишутся параллельно) и опирается только на общие для
//    слоя win_error.hpp (код и текст ошибки) и win_handle.hpp (RAII для
//    дескрипторов, ADR-001) плюс core::log.hpp (журнал).
//
// 7. Чего модуль не трогает: файлы. Он только снимает блокировку — удаляет
//    дальше vfs_delete по FR-6, и тот уже умеет Skip (locked). Модуль ничего не
//    знает про правила, категории и модель core::model: вход — список
//    процессов, выход — отчёт о том, что с ними сделали.
//
// Заголовок намеренно не включает windows.h: объявления используют только
// переносимые типы, поэтому его можно включить оттуда, где Win32 нет (тесты,
// отчёт, CLI), а слой Win32 добавляет <windows.h> сам — так граница слоёв не
// размывается по одному заголовку (то же решение, что в devices.hpp,
// vfs_delete.hpp).
//
// ---------------------------------------------------------------------------
// Порядок работы (важно для чтения кода .cpp)
// ---------------------------------------------------------------------------
//
//   1. planShutdown — предпросмотр без побочных эффектов: имя процесса,
//      проверка «мы это не мы», проверка защищённого имени, проверка, что
//      процесс ещё жив, чтение времени запуска (без него RM не узнаёт процесс).
//   2. closeProcesses: отмена → сбор кандидатов → подтверждение (ровно один
//      вызов колбэка) → фильтрация «подтверждено только то, что показали» →
//      открытие дескрипторов → RmRegisterResources → RmGetList (защита от
//      RmCritical) → RmShutdown → ожидание выхода → повтор с backoff при
//      повторяемом отказе.
//   3. Итог: ShutdownSummary со счётчиками и HRESULT — ровно то, что §4 FR-8
//      кладёт в отчёт, без привязки к форме отчёта.
