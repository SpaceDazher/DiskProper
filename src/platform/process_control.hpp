// Защищённые системные процессы: без них система не грузится или теряет
// пользовательскую сессию. Сравнение не зависит от суффикса: и "lsass", и
// "lsass.exe" — один и тот же процесс.
[[nodiscard]] bool isProtectedProcess(std::wstring_view name) noexcept;

// Копия списка для отчёта и тестов: неизменяемый модулем список отдавать
// ссылкой нельзя, а наружу он нужен — UI показывает, что закрывать нельзя.
[[nodiscard]] std::vector<std::wstring> protectedProcessNames();

// Процесс жив и это тот самый процесс. startTimeTicks == 0 — проверяется только
// PID (с честной оговоркой: переиспользование PID возможно, поэтому движок
// обязан приносить время запуска из RM, где оно есть по определению).
[[nodiscard]] bool isProcessRunning(const ProcessRef& process) noexcept;
[[nodiscard]] bool isProcessRunning(std::uint32_t pid) noexcept;

// Время создания процесса в тиках FILETIME. nullopt — прочитать не удалось
// (нет прав, процесс уже умер). Без него RM не отличит переиспользованный PID.
[[nodiscard]] std::optional<std::uint64_t> readProcessStartTime(std::uint32_t pid) noexcept;

// Имя образа без пути: "chrome.exe". Пустая строка — процесса нет или не
// прочитать (нет прав).
[[nodiscard]] std::wstring queryProcessName(std::uint32_t pid);

// Найти запущенные процессы по именам. Имя сравнивается без учёта регистра и
// без учёта суффикса: и "msedge", и "msedge.exe" подойдут. Нужно правилам
// FR-3/FR-4 (`requiresProcessesClosed`): движок получает список процессов сам и
// не обязан ждать модуль определения блокировок.
[[nodiscard]] std::vector<ProcessRef> findProcessesByName(const std::vector<std::wstring>& names);

// Есть ли хоть один из процессов. Дёшево (один снимок списка) и ничего не
// закрывает: правило, требующее закрытия, должно уметь объяснить «приложение не
// запущено», не трогая его.
[[nodiscard]] bool isAnyProcessRunning(const std::vector<std::wstring>& names) noexcept;

// Мост к модели в обе стороны (§6.3, §4 FR-4/FR-5).
//
// Модель кандидата хранит `lockedBy` как `std::vector<core::ProcessRef>` — UTF-8,
// без времени запута; слой Win32 работает в UTF-16 (§6.3). Перевод живёт здесь,
// а не в движке и не в отчёте, потому что «переведу и забуду проверить» —
// обычный способ показать пользователю имя сломанного процесса.
//
// fromModelProcessRefs: список из модели → предпросмотр. Время запуска модель не
// хранит, и это не беда: planShutdown прочитает его сам, а если прочитать не
// удалось — честно откажется закрывать (см. ProcessRef::startTimeTicks).
[[nodiscard]] std::vector<ProcessRef> fromModelProcessRefs(const std::vector<core::ProcessRef>& refs);

// toModelProcessRefs: результат в модель. Отдаются все записи с ненулевым PID:
