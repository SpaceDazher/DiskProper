// Код, на котором повтор имеет смысл: файл или каталог держит другой процесс
// (антивирус, индексатор, открытый в приложении документ) и скорее всего
// освободится через десятки миллисекунд. Остальные отказы повтором не
// исправляются: ERROR_ACCESS_DENIED на каталоге — это права, а не блокировка.
[[nodiscard]] bool isRetryableWin32(std::int32_t win32Error) noexcept;

// UTF-8 для лога и отчёта: §6.3 (ядро — UTF-8, слой Win32 — UTF-16).
[[nodiscard]] std::string toUtf8Path(std::wstring_view path);

