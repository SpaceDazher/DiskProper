// mrproper-cli: каркас процесса — разбор командной строки, --version, --help
// и таблица кодов возврата.
//
// Спека: §6.2 (строка `cli`: «mrproper-cli scan --json, --plan, --apply —
// headless-режим для CI и e2e»), §8 Этап 0 (проверка «mrproper-cli --version
// печатает версию»), §8 Этап 1-4 (состав команд), §5 (устойчивость, пути),
// §11.4 (машинный вывод), §12 («0 необработанных исключений»).
//
// ---------------------------------------------------------------------------
// Что этот файл делает и что — не делает
// ---------------------------------------------------------------------------
//
// Здесь ровно четыре вещи, и все четыре переносимы (ни windows.h, ни COM, ни
// WinAPI — §6.1): разбор глобальной командной строки, тексты --version и
// --help, реестр команд и единая точка входа runCli, которая разбирает
// глобальную часть и передаёт хвост аргументов нужной команде. Всё это
// проверяется обычным юнит-тестом на любом хосте, без диска и без Windows
// (§11.1) — ради этого разбор и отделён от main.cpp.
//
// Чего здесь нет сознательно:
//
//   * собственной реализации --json, скана и плана: это команды scan, plan,
//     apply, report, rules (задачи 62-65), у каждой свой разбор и свои коды;
//   * перевода кодов команд в коды каркаса. Код команды уходит из runCli как
//     есть: CI обязан отличать «отчёт напечатан» (0) от «набор правил не
//     найден» (3 у scan) и от «ошибка аргументов» (2 у scan, 64 у report), и
//     молчаливое сведение их к нулю превратило бы упавший скан в «мусора нет»;
//   * обработки сигналов: Ctrl+C внутри команды ставит команда (у scan есть
//     свой InterruptGuard, §6.4), каркас смотрит только на её код возврата.
//
// ---------------------------------------------------------------------------
// Контракт на ключи и коды
// ---------------------------------------------------------------------------
//
// Ключи каркаса пишутся ДО имени команды (`mrproper-cli --version`,
// `mrproper-cli help scan`); после имени команды ключи принадлежат команде и
// уходят ей без разбора (`mrproper-cli scan --help` печатает справку scan, а
// не каркаса). Смешивать нельзя: `scan --json` обязан доехать до scan целиком.
//
// Коды возврата каркаса объявлены здесь и только здесь. Коды команд объявлены в
// своих заголовках под другими именами (ScanExit, PlanExit) — общих нет, иначе
// объявление одного имени дважды в одном namespace уронило бы сборку всего, что
// включает оба заголовка.
#pragma once

#include <iosfwd>
#include <string>
#include <string_view>
#include <vector>

namespace mrproper::cli {

// ---------------------------------------------------------------------------
// Коды возврата каркаса
// ---------------------------------------------------------------------------
//
// 2 — ошибка аргументов каркаса: команда не задана, неизвестна или ключ не
//     разобран. Совпадает со ScanExit::Usage (как у grep) и с EX_USAGE из
//     sysexits, которым пользуются report и rules, — CI, который различает
//     ошибку аргументов по коду, не обязан знать, откуда она пришла.
// 70 — необработанное исключение на границе процесса (EX_SOFTWARE, как у
//     report и rules). Спека §12 требует нуля необработанных исключений,
//     поэтому ловит их main.cpp, а не «продолжает как ни в чём не бывало».
// 130 — прервано пользователем (128 + SIGINT). Каркас его не возвращает:
//     прерывание обрабатывает команда; значение зарезервировано, чтобы скрипт
//     знал, что означает 130 в отчёте о прогоне.
enum class CliExit : int {
    Ok = 0,        // команда отработала; успех означает её собственный код
    Usage = 2,     // неизвестная команда/ключ каркаса либо команда не задана
    Internal = 70, // необработанное исключение на границе процесса
};

// Имя программы. Используется в справке, в сообщениях и в командах как
// `mrproper-cli scan --help`: имя одно на весь CLI, чтобы скрипт и человек
// говорили о ней одинаково.
inline constexpr const char* kProgramName = "mrproper-cli";

// ---------------------------------------------------------------------------
// Точки входа команд без собственного заголовка
// ---------------------------------------------------------------------------
//
// cmd_report.cpp и cmd_rules.cpp самодостаточны: заголовков у них нет, а
// контракт объявлен в шапке каждого файла. Здесь — то же объявление, чтобы у
// каркаса не было второй правды об API, который он вызывает, и чтобы
// подключение новой команды не требовало правки чужого файла. Повторное
// объявление в их будущем заголовке компиляции не помешает: объявления
// разрешено повторять, расходиться может только определение.
//
// В отличие от остальных команд у них нет файла-заголовка, поэтому
// «подключить команду» здесь означает ровно одно: добавить имя в реестр и
// вызов в dispatchCommand().
int cmdReport(const std::vector<std::string>& args, std::ostream& out, std::ostream& err);
int cmdRules(const std::vector<std::string>& args, std::ostream& out, std::ostream& err);

// ---------------------------------------------------------------------------
// Версия
// ---------------------------------------------------------------------------

// Версия приложения, например "0.1.0". Совпадает с project(MrProper VERSION)
// в корневом CMakeLists: CMake передаёт MRPROPER_VERSION_STRING, а без него
// берётся значение, совпадающее с project() на текущий момент (как в
// cmd_rules.cpp). Одна строка версии живёт в одном месте — иначе отчёт,
// --version и ресурс .exe разъедутся (§13.1).
[[nodiscard]] const char* appVersion() noexcept;

// Текст `--version`: имя, версия, конфигурация сборки и разрядность.
// Последние две строки — из компиляции и sizeof(void*), а не из реестра:
// версия обязана печататься и на машине, где реестр недоступен.
[[nodiscard]] std::string versionText();

// ---------------------------------------------------------------------------
// Команды
// ---------------------------------------------------------------------------

// Команда, узнанная каркасом. Ни одна из них не реализуется здесь: каркас знает
// только имя, одну строку описания и того, кому передать хвост аргументов.
enum class Command : int {
    None,     // команда не задана (пустая командная строка)
    Help,     // help / --help / -h / help <команда>
    Version,  // version / --version / -V / -v
    Scan,     // SPEC §4 FR-3, FR-4, §8 Этап 2
    Plan,     // SPEC §4 FR-5, §8 Этап 3
    Apply,    // SPEC §4 FR-6, §8 Этап 3
    Report,   // SPEC §4 FR-8, §8 Этап 4
    Undo,     // SPEC §4 FR-7, §7.2, §8 Этап 4 — отмена очистки и возврат из корзины
    Rules,    // SPEC §9.2, §8 Этап 4
    Disks,    // SPEC §4 FR-1, FR-2, §8 Этап 1 — карта разделов, эталонный дамп
    Unknown,  // есть аргумент, команда с таким именем не знакома
};

// Строка реестра команд: имя для разбора и одна строка для --help. Реестр
// один на разбор, --help и диагностику, поэтому «команда есть в справке» и
// «команда вызывается» не могут разойтись.
struct CommandDescription {
    Command id;
    const char* name;
    const char* summary;    // одна строка для общего --help
    const char* detail;     // почему команда не подключена (пусто — подключена)
};

// Все известные команды в порядке справки. Возвращается ссылкой на константу:
// таблица не меняется в рантайме и не должна копироваться на каждый вызов.
[[nodiscard]] const std::vector<CommandDescription>& commandTable() noexcept;

// Команда по имени. Регистр не важен (`Scan` = `scan`): имя набирает человек,
// а в скриптах встречается с любой стороны. Неизвестное имя — Command::Unknown,
// а не исключение: вызывающий сам решает, что с этим делать.
[[nodiscard]] Command commandByName(std::string_view name) noexcept;

// Имя команды для сообщений; для Command::None и Command::Unknown — "?" .
[[nodiscard]] const char* commandName(Command command) noexcept;

// Подключена ли команда (то есть её detail пуст).
[[nodiscard]] bool isAvailable(Command command) noexcept;

// ---------------------------------------------------------------------------
// Разбор командной строки
// ---------------------------------------------------------------------------

// Разобранная командная строка. args — хвост ПОСЛЕ имени команды, дословно:
// каркас не разбирает и не проверяет его, этим занимается команда.
struct CommandLine {
    Command command{Command::None};
    std::string name;                // как написал пользователь (для сообщений)
    std::vector<std::string> args;   // хвост после команды
};

// Разобрать глобальную часть командной строки.
//
// argv — без имени программы (argv[0] отбрасывает main.cpp), как и в
// parseScanOptions/parseApplyOptions: разбор не должен зависеть от того, как
// файл называли на диске.
//
// Правила:
//
//   * `-h`, `--help`, `help`, `help <команда>` — справка;
//   * `-v`, `-V`, `--version`, `version` — версия;
//   * первый иной аргумент — имя команды, остальное уходит в args дословно;
//   * `--` до команды означает «дальше только имя команды»: так можно вызвать
//     команду, если её файл переименовали.
//
// false — с текстом в error; parsed в этом случае не определён.
[[nodiscard]] bool parseCommandLine(const std::vector<std::string>& argv, CommandLine& parsed, std::string& error);

// ---------------------------------------------------------------------------
// Запуск
// ---------------------------------------------------------------------------

// Потоки процесса. Передаются явно по трём причинам: вывод должен уметь уйти
// в строки (тест и e2e), подтверждение `apply` читается не из глобального
// std::cin, а stdout и stderr — разные каналы (§6.2: stdout машина, stderr
// человек) и смешивать их нельзя.
struct CliStreams {
    std::ostream& out;  // машинный stdout: только JSON и то, что запросили в stdout
    std::ostream& err;  // человеческий stderr: справка об ошибке, прогресс, ошибки
    std::istream& in;   // ответы на вопросы (apply --execute)
};

// Общий --help: команды, ключи каркаса, коды возврата и честный список того, что
// в этой сборке не подключено. Один источник правды: ни одна команда не
// перечисляет соседей сама.
[[nodiscard]] std::string usageText();

// Справка по одной команде: каркас не дублирует её текст, а просит саму
// команду напечатать собственную (`<команда> --help`) — иначе две правды
// разъедутся. name — как её написали в `help <name>`, чтобы сообщение об
// опечатке называло именно то, что набрали. Код возврата команды (обычно 0)
// уходит как есть.
[[nodiscard]] int printCommandHelp(std::string_view name, const CliStreams& streams);

// Разобрать глобальную часть и передать хвост команде. Наружу не бросает
// ничего: команды ловят свои исключения сами (SPEC §12), а граница процесса в
// main.cpp — последний рубеж. Код команды возвращается без изменений.
[[nodiscard]] int runCli(const std::vector<std::string>& argv, const CliStreams& streams);

}  // namespace mrproper::cli
