// mrproper-cli: объявления команды «rules» — validate / verify (SPEC §9.2,
// §11 «Стратегия тестирования», §12, ADR-008 «правила никогда не применяются
// без проверки»).
//
// ---------------------------------------------------------------------------
// Зачем файл, если объявление и так есть в args.hpp
// ---------------------------------------------------------------------------
// Объявления cmdRules долгое время жили в args.hpp, потому что у cmd_rules.cpp
// не было своего заголовка. Состояние это было неудобным: контракт команды —
// её коды возврата, её шов для подписи и её правило «args — это то, что после
// имени команды» — читался в файле, который к команде отношения не имеет, а
// сам файл команды держал копию контракта в комментарии. Две правды об одном
// API разъезжаются, и разъедутся снова.
//
// Теперь контракт объявлен здесь, один раз, и это единственное место, где его
// нужно править. Повторное объявление cmdRules в args.hpp остаётся и не
// является ошибкой: повторять объявления разрешено, расходиться может только
// определение. args.hpp нужен каркасу по той же причине, по которой заголовок
// есть у cmd_scan.hpp, cmd_apply.hpp и cmd_disks.hpp: подключение команды не
// должно требовать правки чужого файла.
//
// ---------------------------------------------------------------------------
// Контракт
// ---------------------------------------------------------------------------
//     int cmdRules(const std::vector<std::string>& args, std::ostream& out, std::ostream& err);
//     int cmdRules(int argc, char** argv, std::ostream& out, std::ostream& err);
//
// args — то, что стоит после «rules» (argv[1..argc-1], уже в UTF-8). Второй
// вариант удобен, если разбор аргументов живёт в args.cpp: он сам отбрасывает
// argv[0] и принимает узкие указатели.
//
// Потоки: в out — машинный результат (текстовый итог или --json), в err —
// диагностика и предупреждения. Разделение обязательно, иначе
// «rules validate --json > out.json» испортится прогрессом (SPEC §6.2:
// «--json» — машинный вывод).
//
// Подкоманды: validate (набор разбирается) и verify (полная цепочка §9.2 с
// подписью). Подкоманды update в CLI нет: обновление набора по §9.2 п.1
// выполняет модуль rulesync при запуске приложения, а §9.2 п.5 — кнопка в
// настройках; из командной строки доступны только проверки. Слово «update»
// разбирается как явный отказ, а не как имя каталога набора (см. parseArgs в
// cmd_rules.cpp) — иначе «rules update» молча проверял бы несуществующий
// каталог.
//
// Коды возврата (общая таблица CLI; те же значения в cmd_report.cpp):
//     0   успех;
//    64   неверные аргументы (EX_USAGE) — нет подкоманды, неизвестный флаг,
//         опция без значения;
//    65   данные не годятся (EX_DATAERR);
//    66   нет входа (EX_NOINPUT);
//    69   проверка невозможна (EX_UNAVAILABLE) — в том числе «запрошенная
//         подкоманда не подключена»;
//    70   внутренняя ошибка (EX_SOFTWARE).
//
// ---------------------------------------------------------------------------
// Границы
// ---------------------------------------------------------------------------
// Только core (SPEC §6.1, ADR-004) и стандартная библиотека: ни WinHTTP, ни
// платформенных обёрток, ни engine. Команда должна работать в CI на любой
// машине и не тянуть за собой весь платформенный слой. Шов для Ed25519
// внедряется снаружи (setRuleSignatureVerifier): примитивов подписи в
// репозитории нет, и писать их здесь означало бы «реализацию, которую нечем
// проверить». Пока внедрённого верификатора нет, «rules verify» говорит об
// этом прямо и возвращает 69, а не «успех».
//
// Файл заголовка включается из args.cpp (каркас) и из cmd_rules.cpp
// (определение) и намеренно ничего не знает ни о platform, ни об engine:
// включение команд в каркас не должно тянуть за собой весь граф зависимостей.
#ifndef MRPROPER_CLI_CMD_RULES_HPP
#define MRPROPER_CLI_CMD_RULES_HPP

#include <array>
#include <cstdint>
#include <functional>
#include <iosfwd>
#include <string>
#include <string_view>
#include <vector>

namespace mrproper::cli {

// Примитив проверки подписи Ed25519: манифест байтами (именно так он
// подписывался), публичный ключ и подпись — сырые байты. Реализации в
// репозитории нет; если она появится в платформенном слое, внедряется ровно
// одна копия.
using Ed25519Verify =
    std::function<bool(std::string_view manifestBytes, const std::array<std::uint8_t, 32>& publicKey,
                       const std::array<std::uint8_t, 64>& signature)>;

// Регистрация примитива. Пустая функция означает «проверять подпись нечем», и
// команда «rules verify» сообщает об этом, а не рапортует об успехе.
void setRuleSignatureVerifier(Ed25519Verify verifier);

// Обе точки входа. Ни одна из них не бросает наружу: команда ловит свои
// исключения сама (граница процесса — в main.cpp).
int cmdRules(const std::vector<std::string>& args, std::ostream& out, std::ostream& err);
int cmdRules(int argc, char** argv, std::ostream& out, std::ostream& err);

}  // namespace mrproper::cli

#endif  // MRPROPER_CLI_CMD_RULES_HPP
