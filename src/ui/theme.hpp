// MrProper — тема оформления: схема из реестра, палитра, шрифты с учётом DPI.
// Спека: §5 (строки «Тема» и «DPI»), §7 и §9.1 ADR-003 (тема и DPI — общие
// для обоих путей отрисовки: и Direct2D, и нативные контролы), §7.2 (крупные
// числа, объяснения, иконка риска — всё это краски темы), §5 «Доступность»
// (контраст текста, масштаб шрифта), §10 (неприятно, когда программа слепа к
// настройкам доступности).
//
// Зачем модуль такой. Тема в Windows — это три разные сущности, и их обычно
// путают:
//
//   1. ЧТО выбрал пользователь — режим приложения: следовать системе, светлая
//      или тёмная. Это настройка MrProper, и она переживает перезапуск.
//   2. ЧТО сейчас у системы — AppsUseLightTheme в реестре плюс режим высокой
//      контрастности. Это читается, но не хранится нами.
//   3. ЧЕМ это рисуем — палитра и кегли, то есть числа. Схема без палитры
//      бесполезна: рендереру нужен конкретный RGB, а не «тёмная».
//
// Модуль держит все три и отдаёт наружу только числа: ни одного GDI- или
// D2D-объекта он не создаёт и ни одного окна не знает. Почему так — граница
// слоёв (SPEC §6.1, §6.2): рендер делает renderer (D2D), нативные контролы
// красит вызывающий код (NM_CUSTOMDRAW), а тема — это источник значений.
// Побочный плюс: палитра и типографика — чистые функции чисел, их имеет смысл
// проверять тестами без окна и без Direct2D.
//
// Почему реестр, а не WM_SYSCOLORCHANGE. Спека (§5) называет источником темы
// `AppsUseLightTheme`, и это единственный способ узнать решение пользователя
// до того, как появилось окно: WM_SETTINGCHANGE приходит уже существующему
// окну, а до первого WM_CREATE цвета нужны заранее (панели при создании).
// Реестр читается один раз при старте и перечитывается на WM_SETTINGCHANGE —
// цена одного RegGetValueW несравнима с ценой ошибки «светлая панель на
// тёмной системе».
//
// Почему палитра считается, а не копируется. Тёмная и светлая схемы — не
// инверсия, а два разных набора: инвертированный оранжевый акцент на тёмном
// фоне становится грязно-коричневым. Поэтому здесь базовая таблица на
// схему, а акцент подставляется в неё и ДОПИСЫВАЕТСЯ по контрасту (WCAG 2.x):
// пользовательский акцент, который читается на светлом, может оказаться
// нечитаемым на тёмном, и молча рисовать его было бы ровно тем «слепым к
// настройкам» поведением, от которого предостерегает §5. Контрастные
// функции чистые и переиспользуемые — их же зовёт view_cleanup для иконок
// риска (§7.2).
//
// Высокая контрастность — особый случай, а не третья схема: при ней палитра
// собирается из GetSysColor, потому что пользователь выбрал цвета сам и
// заменять их на «красивые» нельзя. Семантические цвета (успех/предупреждение/
// риск) в этом режиме вырождаются в цвет текста системы — иначе «безопасный»
// пункт стал бы единственным, который читается, а это противоположность
// доступности.
//
// Про DPI. Модуль ничего не настраивает (это делает app_shell:
// SetProcessDpiAwarenessContext(PER_MONITOR_AWARE_V2), SPEC §5) и только
// считает: все кегли хранятся в DIP (1/96 дюйма) и переводятся в пиксели
// функцией MulDiv при отрисовке, поэтому один и тот же код вёрстки работает на
// 100 %, 150 % и 200 % без отдельных веток. Шрифты берутся у системы
// (SystemParametersInfoForDpi + SPI_GETNONCLIENTMETRICS) — так уважается
// выбор шрифта пользователя и его кегля в настройках доступности, а
// моноширинный гарнитуры для чисел (размеры дисков, «12,4 ГБ») подставляется
// нами: системного моноширинного шрифта у Windows нет, а в отчёте и на
// карте дисков столбики цифр должны стоять.
//
// Границы модуля. Чего он НЕ делает:
//   * не создаёт и не хранит D2D/DWrite/GDI-объекты — только значения;
//   * не знает про окна, кроме enableDarkModeForWindow (нужна нативным
//     контролам, SPEC §7: у SysListView32 и SysTreeViewSys нет API «сделай
//     тёмным», есть только недокументированные ординалы uxtheme, поэтому вызов
//     изолирован здесь и безопасен при их отсутствии) и applyNativeColors с
//     applyNativeHeaderTheme (то же правило для фона нативных списков, см.
//     D-75: решение о фоне принимается один раз, здесь, а не в каждом экране);
//   * не занимается локализацией строк (задача 69, src/ui/locale.*): тема
//     даёт цвета и кегли, а не текст;
//   * не логирует в горячем цикле: единственные обращения к реестру и
//     GetSysColor идут при смене темы, а не в цикле отрисовки (§6.4).
//
// Устойчивость. Ни одна функция не бросает исключений: отказ реестра, отказ
// DWM и отсутствие uxtheme дают значения по умолчанию, потому что худшее, что
// может случиться, — неверный цвет, а не упавшее окно (SPEC §5 «устойчивость»).
// Единственное исключение, которого можно ждать от любой функции, —
// std::bad_alloc.
#pragma once

#include <windows.h> // NOLINT(bugprone-suspicious-include) — слой ui, единственное законное место рядом с platform/

#include <commctrl.h> // NOLINT(bugprone-suspicious-include) — LVM_GETHEADER шапки столбцов (см. applyNativeHeaderTheme)

#include <cstdint>
#include <string>
#include <string_view>

#include "core/model.hpp" // core::SafetyLevel: иконка риска §7.2

namespace mrproper::ui::theme {

// ---------------------------------------------------------------------------
// Режим и схема
// ---------------------------------------------------------------------------

// Что выбрал пользователь. Хранится в HKCU\Software\MrProper\UI\ThemeMode:
// «auto» (следовать системе, по умолчанию), «light», «dark».
enum class Mode { Auto, Light, Dark };

// Что фактически применяется. HighContrast — не отдельный выбор пользователя,
// а системный режим доступности, который перебивает и Light, и Dark: человек
// увеличил контраст по медицинским показаниям, и «удобная» тёмная палитра с
// контрастом 4.5:1 тут неуместна.
enum class Scheme { Light, Dark, HighContrast };

// Что изменилось в ответе на сообщение окна. Рендерер перерисовывает только то,
// что реально поменялось: смена темы не должна заставлять пересоздавать шрифты,
// а смена DPI — перечитывать реестр (SPEC §6.4: UI-поток без лишней работы).
enum class Change { None, Scheme, Typography, Dpi };

const char* toString(Mode mode) noexcept;
const char* toString(Scheme scheme) noexcept;

// ---------------------------------------------------------------------------
// Цвет
// ---------------------------------------------------------------------------

// sRGB, 8 бит на канал. Не GDI COLORREF и не D2D1_COLOR_F: те хранят каналы в
// разном порядке (COLORREF — 0x00BBGGRR, то есть красный в младшем байте), и
// путаница между ними даёт цвета, которые выглядят «почти правильно», что
// хуже, чем ошибка. Приведение — в colorRef() и toD2DColor().
struct Color {
    std::uint8_t r{};
    std::uint8_t g{};
    std::uint8_t b{};
    std::uint8_t a{255};

    friend constexpr bool operator==(const Color&, const Color&) = default;
};

// COLORREF для GDI-пути (NM_CUSTOMDRAW, fallback D2D → GDI, SPEC §5): красный
// в младшем байте, альфа отбрасывается — у GDI её нет.
[[nodiscard]] constexpr std::uint32_t colorRef(const Color& color) noexcept {
    return static_cast<std::uint32_t>(color.r) | (static_cast<std::uint32_t>(color.g) << 8) |
           (static_cast<std::uint32_t>(color.b) << 16);
}

// Строка цвета для Direct2D: D2D1_COLOR_F понимает "#AARRGGBB" и "#RRGGBB",
// поэтому рендереру не нужен собственный разбор (SPEC §7, ADR-003).
[[nodiscard]] std::wstring toD2DColor(const Color& color);
[[nodiscard]] std::wstring toD2DColor(const Color& color, bool withAlpha);

// "#RRGGBB" в UTF-8 — для лога и отчёта, где цвет попадает в текст.
[[nodiscard]] std::string toHexUtf8(const Color& color);

// ---------------------------------------------------------------------------
// Контраст (WCAG 2.x)
// ---------------------------------------------------------------------------

// Относительная яркость по формуле WCAG: каналы линеаризуются (гамма 2.4),
// затем берётся взвешенная сумма 0.2126 R + 0.7152 G + 0.0722 B. Функция
// чистая: палитра, выбранная из таблицы, проверяется той же формулой, что и
// документация WCAG, иначе «контраст 4.5:1» в коде и в требованиях — разные
// числа.
[[nodiscard]] double relativeLuminance(const Color& color) noexcept;

// Отношение контраста, 1.0…21.0. 4.5 — обычный текст (WCAG AA), 3.0 — крупный
// текст и границы элементов (WCAG 1.4.11), 7.0 — AAA.
[[nodiscard]] double contrastRatio(const Color& first, const Color& second) noexcept;

// Белый или чёрный — какой из двух лучше читается на фоне. Для акцентных
// кнопок это решает, будет ли текст «Очистить» видимым, а не только «каким-то».
[[nodiscard]] Color readableOn(const Color& background, double minRatio = 4.5) noexcept;

// Двигает цвет к белому или к чёрному, пока контраст с фоном не достигнет
// минимума. Ничего не «подкрашивает наугад»: если цель достижима, цвета
// останутся узнаваемо тем же оттенком, просто с нужной светлотой. Если не
// достижима ни одна сторона (фон того же тона, что и текст), возвращается
// противоположный по светлоте цвет — нечитаемый фон всё равно должен быть
// помечен чем-то максимально контрастным.
[[nodiscard]] Color ensureContrast(const Color& foreground, const Color& background, double minRatio) noexcept;

// ---------------------------------------------------------------------------
// Палитра
// ---------------------------------------------------------------------------

// Именованные роли, а не «цвет1/цвет2»: экран «Очистка» показывает
// «безопасный/требует проверки/рискованный» (FR-4, §7.2), и цвет риска должен
// прийти из темы, а не из литерала в коде вида. Тёмная и светлая схемы
// различаются десятками значений — хранить их рядом в одной структуре
// читаемее, чем две ветки в коде отрисовки.
struct Palette {
    Color windowBackground;   // фон окна
    Color surface;            // карточка, панель, строка списка
    Color surfaceAlt;         // чередующаяся строка (зебра), вложенная панель
    Color surfaceHover;       // наведение мыши
    Color surfaceSelected;    // выделение строки
    Color border;             // рамка карточки и контрола
    Color divider;            // разделитель строк, тоньше рамки
    Color textPrimary;        // основной текст
    Color textSecondary;      // пояснения, подписи, единицы измерения
    Color textDisabled;       // неактивные элементы (контраст по WCAG не
                              // обязателен: элемент недоступен по определению)
    Color accent;             // основной акцент (кнопка, выделение, фокус)
    Color accentHover;
    Color accentPressed;
    Color textOnAccent;       // текст НА акценте: белый или чёрный, решает контраст
    Color focusRing;          // прямоугольник фокуса: клавиатура обязана его видеть
    Color success;            // освобождено, безопасно
    Color warning;            // требует внимания
    Color danger;             // отказ, рискованное действие

    // Цвета уровней риска из core::SafetyLevel. Отдельные поля, а не алиасы:
    // в тёмной схеме «успех» зелёный ярче, чем в светлой, и привязка к
    // success/danger была бы враньём в одной из двух схем.
    Color riskSafe;
    Color riskReview;
    Color riskRisky;
};

// Палитра для схемы с указанным акцентом. Чистая функция от чисел: та же
// палитра получается на любой машине и её имеет смысл проверять тестом.
[[nodiscard]] Palette makePalette(Scheme scheme, const Color& accent) noexcept;

// ---------------------------------------------------------------------------
// Нативные списки и деревья
// ---------------------------------------------------------------------------

// Что видно в строке нативного контрола. background — цвет, который сейчас
// будет залит, text — цвет, который на ЭТОМ фоне читается. Пара, а не два
// независимых числа: «фон темы» и «текст темы» брались раньше по отдельности,
// и в тёмной схеме оба назывались «правильными», пока не оказывались
// одного цвета (D-75).
struct NativeRow {
    Color background;
    Color text;
};

// Строка нативного списка или дерева.
//   selected  — строка выбрана: фон берётся из «выделения», подпись — та, что
//               на этом фоне читается (одно правило и для светлой, и для тёмной
//               схемы: выделение в них противоположно по светлоте);
//   distinct  — строка с отличающимся фоном: «зебра» нечётных строк либо
//               недоступная строка;
//   muted     — подпись приглушённая, но ЧИТАЕМАЯ. Не textDisabled: у
//               недоступной строки («диск не читается», «правило выключено»)
//               смысл надо прочесть, а элемент недоступен не целиком — иначе
//               ворота «текст в области строк» видят ровно тот отказ, который
//               здесь и чинится.
[[nodiscard]] NativeRow nativeRow(const Palette& palette, bool selected, bool distinct, bool muted) noexcept;

// Цвет подписи ПРОТИВ ФАКТИЧЕСКОГО фона: если контраст ниже 4.5:1 (WCAG AA),
// берётся противоположная сторона — сначала сдвигом к белому или чёрному, а
// если и она не дотягивает, то краем (см. ensureContrast). Функция вынесена
// отдельно от nativeRow для строк, у которых подпись задана ролью, а не
// строкой палитры: «ошибка» и «предупреждение» в журнале.
[[nodiscard]] Color nativeTextOn(const Color& foreground, const Color& background) noexcept;

// Заголовок столбцов: тот же контраст, своё место. pressed — столбец под
// мышью или нажат (у comctl32 это CDIS_HOT).
[[nodiscard]] NativeRow nativeHeader(const Palette& palette, bool pressed) noexcept;

// Какой нативный контрол красим. Список и дерево принимают разные сообщения
// о цветах, но решение о фоне у них одно, и перечисление вида контрола —
// единственное, чем оно отличается.
enum class NativeControl { List, Tree };

// Фон и подписи нативного контрола — одно решение для всех экранов (D-75).
//
// Что было. Экран задавал фон дважды: ListView_SetBkColor(palette.surface), а
// затем enableDarkModeForWindow(list, Dark), и подтема DarkMode_Explorer
// пересобирала оформление контрола и возвращала ему СИСТЕМНЫЙ фон
// (COLOR_WINDOW/COLOR_BTNFACE). NM_CUSTOMDRAW при этом красил подпись в
// palette.textPrimary — в тёмной схеме это белый по белому: измеренная область
// строк «Дисков» давала 0 пикселей текста из 114 380 при десяти непустых
// строках, тогда как тот же бинарник в светлой схеме давал 12 128 из 234 576.
// «Настройки» в тёмной схеме рисовались системным COLOR_BTNFACE (240,240,240)
// независимо от палитры — то есть каждый экнал решал по-своему, и решал плохо.
//
// Что стало. У каждого нативного контрола ровно один хозяин фона:
//   * строки списка и узлы дерева — сообщения LVM_SETBKCOLOR/TVM_SETBKCOLOR
//     плюс заливка NM_CUSTOMDRAW (fillNativeRow). Тёмный режим им НЕ
//     включается: подтема DarkMode_Explorer перекрывает заданный фон и
//     возвращает контролу системный цвет;
//   * шапка столбцов — подтема DarkMode_Explorer у самого окна SysHeader32
//     (см. applyNativeHeaderTheme).
// Светлые полосы прокрутки у списка — плата за первый пункт: подтемы, которая
// красит их в палитру, не существует, а читаемость важнее вида.
void applyNativeColors(HWND control, NativeControl kind, const Palette& palette) noexcept;

// WM_CTLCOLORHDR в заголовках Windows 10 SDK отсутствует: это документированное
// сообщение Win32 (шапке столбцов отправляет его родитель — окно списка), но
// объявления в commctrl.h нет. Константа дана тут, чтобы три экрана не заводили
// свою.
inline constexpr UINT WM_CTLCOLORHDR = WM_USER + 66;

// Шапка столбцов списка. Это отдельное окно (SysHeader32), фон которому задаёт
// не список, а сама шапка, и NM_CUSTOMDRAW от неё до родителя списка на этой
// сборке Windows НЕ доходит: замер дал ноль доставленных уведомлений за весь
// обход страниц, а шапка при этом оставалась системной (240,240,240 в тёмной
// схеме). Поэтому у шапки один хозяин фона — документированная подтема
// «тёмного» (ADR-003), а не попытка красить её извне. В светлой схеме вызова
// нет: там шапка системная и правильная.
void applyNativeHeaderTheme(HWND list, Scheme scheme) noexcept;

// Прямоугольник строки списка по индексу. Нужен потому, что nmcd.rc у
// NM_CUSTOMDRAW на стадии CDDS_ITEMPREPAINT НЕ является прямоугольником
// строки: замерено на этой Windows — значения мусорные (например left=760,
// top=32766, bottom=0), и заливка по такому прямоугольнику не рисует ничего.
// Спрашивать у самого контрола — единственный способ узнать, где строка.
// Координаты — как у клиентской области списка, то есть в ту же систему, что и
// DC из NM_CUSTOMDRAW. Только для списка: у дерева прямоугольник узла в
// nmcd.rc заполнен, а индекс узла — не число, а HTREEITEM.
[[nodiscard]] bool nativeListItemRect(HWND list, int index, RECT& box) noexcept;

// Заливка строки (её фона) цветом темы. Модуль не владеет GDI: кисть создаётся
// и удаляется внутри вызова, наружу уходят только цвета.
void fillNativeRow(HDC dc, const RECT& box, const Color& background) noexcept;

// Цвет для уровня риска кандидата (FR-4, §7.2: «иконка риска» у каждого
// элемента списка). При высокой контрастности все три сходятся в цвет текста
// системы — так и сделано в makePalette.
[[nodiscard]] Color riskColor(const Palette& palette, core::SafetyLevel level) noexcept;

// ---------------------------------------------------------------------------
// Шрифты и метрики
// ---------------------------------------------------------------------------

// Роль текста. Кегли хранятся в DIP, а не в пикселях: при 150 % один и тот же
// FontDesc даст и другой кегль, и другой отступ — вёрстка не должна знать про
// DPI (SPEC §5).
enum class FontRole { Caption, Body, BodyStrong, Subtitle, Title, Metric, Mono, MonoStrong };

// Описание шрифта. weight — числа DWRITE_FONT_WEIGHT (400 normal, 600
// semi-bold, 700 bold): те же значения нужны DirectWrite для CreateTextFormat
// и GDI для lfWeight, поэтому своя шкала не заводится.
struct FontDesc {
    std::wstring family{L"Segoe UI"};
    double sizeDip{14.0};
    int weight{400};
    bool italic{false};
    bool fixedPitch{false};  // моноширинный: числа в столбике не «прыгают»

    friend bool operator==(const FontDesc&, const FontDesc&) = default;

    // Высота в пикселях под конкретный DPI (округление, а не голое умножение
    // double: на 150 % 14 DIP → 21 px ровно, а «почти целое» накапливается
    // вложенными элементами списка и даёт разъезжающиеся строки).
    [[nodiscard]] int pixelHeight(unsigned dpi) const noexcept;

    // LOGFONTW для GDI-пути (fallback, когда Direct2D недоступен, SPEC §5).
    // Только заполняет структуру: HFONT создаёт вызывающий (он же владеет и
    // удаляет), модуль не держит GDI-ресурсов.
    [[nodiscard]] LOGFONTW toLogFont(unsigned dpi) const noexcept;
};

// Типографика: восемь ролей вместо сырых кеглей в коде отрисовки, чтобы
// «подпись» и «заголовок» не отличались на 2 px от того, чем они выглядят в
// макете, и чтобы масштаб текста (§5, доступность) менялся в одном месте.
struct Typography {
    FontDesc caption;
    FontDesc body;
    FontDesc bodyStrong;
    FontDesc subtitle;
    FontDesc title;
    FontDesc metric;      // крупные числа: «12,4 ГБ»
    FontDesc mono;        // таблицы и идентификаторы
    FontDesc monoStrong;

    [[nodiscard]] const FontDesc& forRole(FontRole role) const noexcept;
};

// Метрики под конкретный DPI. Держит и сам dpi, и производные величины:
// пересчитывать масштаб в каждом обработчике WM_PAINT — верный способ забыть
// про одно из двух мест.
struct Metrics {
    unsigned dpi{96};
    double scale{1.0};     // dpi / 96
    double fontScale{1.0}; // пользовательский масштаб текста (§5, доступность)

    // DIP → пиксели с округлением до целого: вёрстке нужны целые координаты,
    // а «почти целое» накапливается вложенными элементами списка.
    [[nodiscard]] int dip(double value) const noexcept;
    [[nodiscard]] double undo(int pixels) const noexcept;  // пиксели → DIP
};

// Метрики для DPI. dpi == 0 трактуется как «системный» (см. dpiForSystem).
[[nodiscard]] Metrics metricsForDpi(unsigned dpi, double fontScale = 1.0) noexcept;

// Типографика под DPI. Гарнитура UI-шрифта берётся у системы, кегли — из
// типографского масштаба модуля: системные 9 pt — это кегль заголовка окна, а
// текст приложения на 12 px читается мелко, поэтому гарнитуру мы уважаем, а
// кегль задаём свой.
[[nodiscard]] Typography makeTypography(unsigned dpi, double fontScale = 1.0) noexcept;

// ---------------------------------------------------------------------------
// Системные источники
// ---------------------------------------------------------------------------

// Режим из HKCU\Software\MrProper\UI\ThemeMode. Отсутствие ключа, битое
// значение и отказ доступа — все три дают Mode::Auto: «следовать системе»
// безопаснее угаданного значения.
[[nodiscard]] Mode storedMode() noexcept;
[[nodiscard]] bool storeMode(Mode mode) noexcept; // false — реестр не пишется

// Пользовательский масштаб текста в процентах, 75…200. Больше 200 раздувает
// списки так, что полосы прокрутки съедают окно, меньше 75 текст перестаёт быть
// читаемым целиком — границы берутся из настроек самой Windows, где
// настраивается как раз масштаб текста.
[[nodiscard]] unsigned storedFontScalePercent() noexcept;
[[nodiscard]] bool storeFontScalePercent(unsigned percent) noexcept;

// Схема системы. Порядок решения не «какой API ответил», а «что важнее для
// пользователя»: высокая контрастность перебивает всё, затем AppsUseLightTheme
// (§5), затем светлая как безопасный отказ по умолчанию.
[[nodiscard]] Scheme systemScheme() noexcept;

// Акцент системы: DwmGetColorizationColor, при отказе — ColorizationColor из
// реестра, при отказе — синий Windows. Акцент, а не «тема»: цвет панели задач и
// цвет выделения в Windows 11 разошлись, и брать надо тот, что виден в
// интерфейсе.
[[nodiscard]] Color systemAccent() noexcept;

// DPI. dpiForWindow — per-monitor V2 (SPEC §5); dpiForSystem нужен до
// появления окна, когда неявная DPI-контекста ещё не определена.
[[nodiscard]] unsigned dpiForSystem() noexcept;
[[nodiscard]] unsigned dpiForWindow(HWND window) noexcept;

// Тёмный режим нативного контрола. У SysListView32/SysTreeViewSys нет
// документированного «сделай тёмным»: официальный путь — SetWindowTheme с
// подтемой DarkMode_Explorer, а часть эффектов (цвет рамки, полосы прокрутки)
// доступна только через недокументированные ординалы uxtheme. Ординалы
// берутся по имени-по-номеру и проверяются на nullptr, поэтому на сборке без
// них (или на старой Windows) вызов безопасно ничего не делает. Возвращает
// false, если тёмный режим применить не удалось, — вызывающий просто рисует
// контрол светлым, как умеет.
//
// ВНИМАНИЕ, граница применения. Эту функцию НЕ вызывают для списков и
// деревьев: подтема DarkMode_Explorer перекрывает фон, заданный
// ListView_SetBkColor, и возвращает контролу системный цвет (D-75, см.
// applyNativeColors). Для окна приложения вызов остаётся в силе — там тьма
// красит рамку и заголовок окна, а фон содержимого рисует сам экран.
[[nodiscard]] bool enableDarkModeForWindow(HWND window, Scheme scheme) noexcept;

// Что изменилось в ответе на сообщение окна. Вынесено отдельно, чтобы
// app_shell не содержал таблицы строковых сравнений, а логика «какое сообщение
// означает смену темы» жила рядом с темой.
[[nodiscard]] Change classifyMessage(UINT message, WPARAM wParam, LPARAM lParam) noexcept;

// ---------------------------------------------------------------------------
// Контекст темы
// ---------------------------------------------------------------------------

// Состояние темы приложения: режим пользователя, применённая схема, палитра,
// типографика и метрики под текущий DPI. Блокировок нет намеренно: объект
// принадлежит UI-потоку, единственному, которому принадлежат и окно, и
// D2D-ресурсы (SPEC §6.4). Пересчёт — на смену темы, а не в цилле
// отрисовки; единственное, что делается на каждом WM_PAINT, — взять
// готовые значения.
class Theme {
public:
    // Читает настройки, определяет схему и строит палитру под системный DPI.
    Theme();

    // То же плюс метрики окна: WM_DPICHANGED до первого кадра.
    explicit Theme(HWND window);

    // Перечитать систему (WM_SETTINGCHANGE, WM_THEMECHANGED,
    // WM_SYSCOLORCHANGE) и пересчитать палитру.
    void reload() noexcept;

    // Разобрать сообщение окна и применить то, что в нём изменилось.
    // Возвращает true, если состояние темы стало другим и нужен перерисовка.
    bool applyMessage(UINT message, WPARAM wParam, LPARAM lParam) noexcept;

    // Переключить режим. Режим сохраняется в реестре: выбор темы, сделанный
    // один раз, не должен сбрасываться при каждом запуске. Возвращает false,
    // если режим не изменился (в т. ч. когда реестр недоступен, но тогда
    // применяется новый режим в текущем сеансе — об этом сообщает лог).
    bool setMode(Mode mode) noexcept;

    // Масштаб текста, 75…200. Значение вне диапазона поджимается, а не
    // отвергается: кнопка «крупнее» не должна молча ничего не делать.
    bool setFontScalePercent(unsigned percent) noexcept;

    // Смена DPI окна. Палитра не меняется (она в процентах яркости, а не в
    // пикселях), меняются только кегли и масштаб.
    void setDpi(unsigned dpi) noexcept;

    [[nodiscard]] Mode mode() const noexcept;
    [[nodiscard]] Scheme scheme() const noexcept;
    [[nodiscard]] const Palette& palette() const noexcept;
    [[nodiscard]] const Typography& typography() const noexcept;
    [[nodiscard]] const Metrics& metrics() const noexcept;
    [[nodiscard]] unsigned fontScalePercent() const noexcept;

    [[nodiscard]] const FontDesc& font(FontRole role) const noexcept;

    // Метрики под DPI произвольного окна: у нас окно одно, но во время
    // перетаскивания между мониторами WM_DPICHANGED приходит раньше, чем
    // применится новый dpi, и вёрстке нужно знать, куда она считает.
    [[nodiscard]] Metrics metricsFor(HWND window) const noexcept;

    // Значения под DPI окна: шрифты и метрики для отрисовки прямо сейчас.
    [[nodiscard]] Typography typographyFor(HWND window) const;
    [[nodiscard]] FontDesc fontFor(FontRole role, HWND window) const;

private:
    Mode mode_{Mode::Auto};
    Scheme scheme_{Scheme::Light};
    unsigned fontScalePercent_{100};
    Palette palette_{};
    Typography typography_{};
    Metrics metrics_{};

    void applyScheme() noexcept;
    void applyTypography(unsigned dpi) noexcept;
};

} // namespace mrproper::ui::theme
