// Отмена очистки как решение, а не как перенос: что можно вернуть, куда это
// вернётся и что спросить у пользователя, прежде чем что-то трогать.
//
// Спека: §4 FR-7 («восстановление: полное или частичное (по элементу), проверка
// конфликтов (существующий файл — не перезаписывать, спросить)», «кросс-томовое
// перемещение = копирование: честно показываем „это займёт время“»),
// §7.2 («отмена (Ctrl+Z) доступна, пока транзакция не „схлопнулась“»),
// §6.1 (слои: engine — оркестрация, без Win32 и без UI), §6.2 (`engine::*` —
// «оркестрация, план, исполнение, транзакции, undo»), §6.4 (отмена
// `std::stop_token`, проверка каждые 256 элементов, прогресс в UI-поток),
// §4 FR-6 (Restart Manager — «кто держит», блокировки не фатальны),
// §5 (устойчивость: ни один отказ не роняет процесс; никаких прав на старте),
// §8 (отчёт: список выполненных операций и ошибки), §12 (все ошибки в логе с
// путём и HRESULT), §9.1 ADR-005 (своя корзина) и ADR-004 (Core без Windows).
//
// ---------------------------------------------------------------------------
// Зачем модуль, если восстановление уже есть у соседей
// ---------------------------------------------------------------------------
//
// Отмена в проекте разложена на три слоя, и каждый закрывает свою часть —
// иначе «перезаписать или спросить» оказалось бы в двух местах и разошлось бы:
//
//   core::undo — переносимое решение (ADR-004). Строит план восстановления из
//   снимка состояния целей, разбирает конфликты, задаёт вопросы пользователю,
//   пересчитывает план по ответам, считает итог и помечает возвращённое. Ни
//   файлового ввода-вывода, ни Windows, ни часов. Это ровно то, ради чего
//   писался `core/undo` (задача W11/09) — в том числе «частичное по элементу».
//
//   platform::vfs_trash — байты. `restoreTrashItem` возвращает элемент на место
//   (переименованием или копированием), сам отказывается трогать занятое место
//   без права перезаписи, применяет mtime и ACL ИЗ МАНИФЕСТА и убирает копию
//   из корзины. Отказа не бросает — отдаёт `TrashStatus` с кодом Win32.
//
//   engine::undo_service (этот модуль) — оркестрация между ними: поднять
//   транзакции с диска, снять снимок состояния целей настоящей ФС (существует,
//   какого типа, занято ли, есть ли родитель, есть ли место), превратить это в
//   план с вопросами, принять ответы, исполнить план с перепроверкой «занято
//   place» перед каждым переносом и привести манифест в соответствие с фактом.
//
//   engine::trash_service (задача W12/59) — обратная сторона: положить,
//   вытеснить по лимитам, почистить. Он же умеет исполнить `core::RestorePlan`.
//   Разница видна в словаре решений: `core::RestoreAction` — это {Restore,
//   Overwrite, Conflict, Missing}, то есть «перезаписать всё, где занято» —
//   один флаг на всю транзакцию. `core::RestoreDecision` — это {Restore, Skip,
//   Rename, Overwrite} плюс `needsUserDecision` и тексты вопросов, то есть
//   решение по КАЖДОМУ элементу. FR-7 требует именно второго («спросить»), и
//   поэтому «перезаписывать или спросить» живёт здесь, а исполнение плана —
//   здесь же (сервису trash_service достаточно было не решать это вовсе).
//
// ---------------------------------------------------------------------------
// Формат манифеста: один, а не два
// ---------------------------------------------------------------------------
//
// На диске манифест пишет `engine::trash_service`, и его формат — `core::trash`
// (`manifest.json`, схема `core::kTrashManifestSchema`). Модуль читает и пишет
// РОВНО этот формат: он переводит транзакцию в проекцию `core::UndoTransaction`
// (всё, что нужно для решения), прогоняет решение через `core::undo` и
// переводит результат обратно. Свой формат манифеста у модуля нет и не
// появится: два формата в одном каталоге корзины означали бы, что половина
// транзакций либо не читается, либо читается как чужая.
//
// ---------------------------------------------------------------------------
// Правила, которые модуль соблюдает по построению
// ---------------------------------------------------------------------------
//
// 1. Ничего не бросает наружу, кроме std::bad_alloc. Отказ — это состояние в
//    структуре результата плюс код Win32 и путь: FR-6 требует, чтобы отказ по
//    одному элементу не останавливал прогон, а §5 — чтобы ни один отказ не
//    ронял процесс. Поэтому `core::TrashError` (недопустимый txId при склейке
//    пути) и `core::UndoError` (план не сошёлся) ловятся в двух местах.
//
// 2. Ничего не перезаписывается без явного решения пользователя (FR-7). Три
//    уровня защиты, и все три нужны: план по умолчанию ставит `Skip` +
//    `needsUserDecision` на всё занятое; перед самым переносом модуль ещё раз
//    спрашивает ФС (файл мог появиться после плана); и платформа сама отказывает
//    на занятом месте без права перезаписи. Решение пользователя «перезаписать»
//    превращается в перезапись только в одном месте — в `RestoreAction`.
//
// 3. Ответ «не отвечать» — это «пропустить», а не «перезаписать» (FR-7).
//    Пересчёт по ответам делает ядро (`core::applyRestoreAnswers`), и запись без
//    ответа остаётся пропущенной. Модуль не имеет права превращать «молчание» в
//    действие: это делал бы один неверно прочитанный вопрос.
//
// 4. Часы приходят параметром (`now`), а не читаются в модуле: иначе лимит
//    «7 дней» и отметка времени восстановления нельзя было бы проверить тестом с
//    фиксированным «сейчас» — а возрастной лимит FR-7 это ровно вычисление от
//    «сейчас».
//
// 5. Перед каждым переносом цель перепроверяется, а не доверяется снимку из
//    плана: между планом и исполнением проходит время, в течение которого файл
//    мог появиться (это и есть гонка, из-за которой «существующий файл —
//    не перезаписывать» должно быть свойством исполнения, а не только плана).
//
// 6. Отмена кооперативная и проверяется раз в `cancelCheckEvery` элементов
//    (§6.4). Оставшиеся записи получают статус «не выполнено» — их честно видно
//    в итоге, потому что «молча» их выкинуть значило бы показать в отчёте
//    полное восстановление.
//
// 7. Манифест пишется только после факта. Сначала перенос, потом отметка
//    возвращённого: обратный порядок при отмене или сбое оставил бы транзакцию,
//    которая обещает вернуть то, чего в корзине уже нет. Отказ записи манифеста
//    не откатывает восстановление (данные уже на месте) и попадает в результат
//    отдельной строкой — приложение обязано перечитать корзину.
//
// 8. Каталог транзакции сносится только когда возвращено всё и манифест записан:
//    тогда в каталоге не остаётся ничего, что можно было бы потерять. Каталог с
//    невосстановленными элементами не трогается никогда — там лежит единственная
//    копия данных, которые не вернулись.
//
// 9. Занятость спрашивается у Restart Manager (engine::locks, FR-6), а не
//    угадывается по коду ошибки: отказ RM не равен «файл свободен». Опрос идёт
//    только для целей, которые существуют, — «занятый несуществующий файл» не
//    бывает, а лишние сессии RM на тысяче элементов стоят секунд.
//
// 10. Модуль не создаёт потоков, не таймеров и не тихих мест. Он синхронен, как
//     остальная оркестрация движка: параллелизм решает пул исполнителя (§6.4).
//
// 11. Если приложение держит открытый `engine::trash_service::TrashService`, его
//     журнал живёт в памяти и после восстановления разойдётся с диском: там
//     осталась транзакция, которой уже нет. Вызывающий обязан сделать
//     `TrashService::refresh()` — это ровно то, для чего он и написан.
