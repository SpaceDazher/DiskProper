// Мост «кандидат очистки → core::scoreCandidate»: подстановка данных скоринга
// (SPEC §4 FR-4). Спека: §4 FR-4 (SafetyLevel, ConfidenceScore, Reasons),
// §6.2 (core::scoring — ConfidenceScore/SafetyLevel/ранжирование; engine:* —
// оркестрация), §6.3 (модель CleanupCandidate), §12 («ни один элемент не
// удаляется без видимого объяснения и уровня риска»), §4 FR-9 (смена
// safety-уровня правила — значит, скоринг умеет переоценивать).
//
// ---------------------------------------------------------------------------
// Зачем модуль, если скоринг уже есть
// ---------------------------------------------------------------------------
// Ядро (core::scoring) — чистая функция: дали ScoreInput, получили Score. Это
// сделано ради тестируемости без диска (ADR-004), и за это платится тем, что
// ScoreInput приходится наполнять вручную. Между кандидатом из скана и этими
// полями стоит четыре разных источника правды:
//
//   * правило (core::rules) — объявленный уровень безопасности, minAgeDays и
//     требование закрытых приложений;
//   * кандидат (core::model::CleanupCandidate) — возраст, объём, занятость;
//   * окружение прогона — «сейчас», корень профиля пользователя, системные
//     корни, «.Restart Manager отработал или нет»;
//   * сам шаблон правила — широкий он или закрепляет точное имя каталога.
//
// Разложить это по трём вызывающим (сборщик кандидатов, координатор скана,
// планировщик) — значит размножить решение и получить три разных ответа на
// один и тот же кандидат. Модуль существует, чтобы подстановка была ровно в
// одном месте, а решение core::scoreCandidate — ровно в одном экземпляре.
//
// ---------------------------------------------------------------------------
// Граница модуля
// ---------------------------------------------------------------------------
// Внутри:
//   * проверка «путь внутри корня профиля / внутри системного корня»;
//   * признак «шаблон правила не закрепляет конкретного имени»;
//   * вызов core::scoreCandidate и запись вердикта в кандидата;
//   * порог отбора: элемент с уверенностью ниже порога по умолчанию не
//     выбирается (core::kDefaultConfidenceThreshold = 50).
//
// Снаружи (сознательно НЕ здесь):
//   * сбор и нормализация путей, белый список защищённых каталогов, проверка
//     «путь внутри корня правила» как запрет на удаление —
//     platform::vfs_paths. Здесь тот же вопрос решается как эвристика для
//     уверенности и сравнением ТЕКСТА уже нормализованного пути; запретом на
//     удаление это быть не может и авторитетом не является;
//   * «кто держит файл» (engine::locks + platform::restart_manager) — сюда
//     приходит уже заполненный candidate.lockedBy и признак
//     processClosedStateKnown;
//   * обход, отмена, прогресс (engine::scan_coordinator);
//   * выбор пользователя, агрегаты, dry-run (engine::plan_builder +
//     core::plan) — мост только ставит оценку и порог, решение «удалять ли»
//     принимает план, потому что у него есть профиль и явный выбор человека;
//   * часы и окружение. Своего источника времени у модуля нет: now приходит
//     в ScoringContext один раз на прогон, чтобы все кандидаты считались от
//     одной точки.
//
// ---------------------------------------------------------------------------
// Инварианты
// ---------------------------------------------------------------------------
//   1. Оценка идемпотентна: список причин кандидата пересобирается заново, а
//      не дописывается. Причины сборщика отделяются от причин моста по
//      kVerdictPrefix, поэтому и повторный applyScore того же вердикта, и
//      переоценка уже оценённого кандидата (FR-9: пользователь сменил уровень
//      правила) не дают в отчёте двух копий одной строки.
//   2. Числа оценки считает только core::scoreCandidate. Мост добавляет к ним
//      ровно одну поправку — kUndescribedPathPenalty за кандидата без
//      правила, потому что FR-4 прямо называет «нет правила» снижателем
//      уверенности. Все прочие снижения живут в ядре и покрыты его тестами.
//   3. Мост ничего не понижает до zero без причины: отсутствие данных
//      (неизвестный профиль, неизвестное время записи) даёт объяснение и
//      осторожную подстановку, а не молчаливую оценку.
//   4. Ни одна функция не бросает исключений намеренно (SPEC §5 «устойчивость»
//      распространяется и на движок). Единственный источник исключения —
//      std::bad_alloc при выделении строк.
//
// ---------------------------------------------------------------------------
// Слой
// ---------------------------------------------------------------------------
// Файл не включает windows.h: подстановка данных не зависит от Windows, и её
// можно покрыть обычными юнит-тестами на хосте (SPEC §11 п.1). Границу слоёв
// (ADR-004) это не размывает — мост зависит только вниз, на core.
#pragma once

#include <cstdint>
#include <string>
#include <string_view>
#include <unordered_map>
#include <vector>

#include "core/model.hpp"
#include "core/rules.hpp"
#include "core/scoring.hpp"

namespace mrproper::engine::scoring_bridge {

// ---------------------------------------------------------------------------
// Порог отбора
// ---------------------------------------------------------------------------

// Порог отбора по умолчанию: уверенность ниже него не даёт элементу попасть
// в план без явного выбора пользователя. Значение живёт в ядре
// (core::kDefaultConfidenceThreshold, оттуда же core::kPlanDefaultConfidenceThreshold —
// это ОДНО и то же число), мост только называет его в своей терминологии.
// SPEC §4 FR-4: «ConfidenceScore (0–100)… Снижают: неизвестный путь, нет
// правила, файл создан сегодня…», §12: «ни один элемент не удаляется без
// видимого объяснения».
inline constexpr int kSelectionThreshold = core::kDefaultConfidenceThreshold;  // 50

// Префикс строки вердикта в списке причин кандидата. По нему мост узнаёт свой
// собственный блок объяснений и пересобирает список при переоценке, а не
// дописывает вторую копию (FR-9: пользователь сменил уровень правила — оценка
// считается заново). Публичная константа: план, отчёт и UI читают причины как
// есть, но могут отличить вердикт скоринга от причин сборщика.
inline constexpr std::string_view kVerdictPrefix = "вердикт скоринга: ";

// Скидка за кандидата, чьё правило в наборе не найдено. FR-4 называет «нет
// правила» среди снижателей уверенности, а в ядре такого флага нет: ядро
// честно не знает про набор правил, мост знает. Правило отсутствует — путь не
// описан ни одной строкой набора, совпадение случайное, и элемент тем более
// не должен выбираться сам.
inline constexpr int kUndescribedPathPenalty = 25;

// ---------------------------------------------------------------------------
// Данные прогона
// ---------------------------------------------------------------------------

// Факты, которых нет ни в правиле, ни в кандидате. Наполняет координатор
// скана (engine::scan_coordinator) один раз на прогон и передаёт мосту дальше.
struct ScoringContext {
    // «Сейчас» в unix-секундах. Обязательно: без него возраст кандидата не
    // оценивается вовсе, а кандидат без объяснения недопустим (§12). Ноль —
    // часы не передали, мост не выдумывает время.
    std::int64_t now{};

    // Корень профиля пользователя («C:\Users\Daniil») — от платформы.
    // Пусто = профиль неизвестен, и мост считает кандидата пользовательским:
    // лишние 15 баллов уверенности дешевле, чем молчаливое «это не данные
    // пользователя» (FR-4 перечисляет «файл в пользовательских данных» среди
    // снижателей).
    std::string userProfileRoot;

    // Системные корни («C:\Windows», «C:\Program Files», …) — от платформы.
    // Пусто = проверка не выполнялась: системным считается только то, что
    // действительно лежит под переданным корнем. Ответственность за
    // заполнение — на координаторе, иначе понижение Safe→Review (FR-4) не
    // сработает никогда.
    std::vector<std::string> systemRoots;

    // Restart Manager отработал (engine::locks): true — про приложения,
    // использующие файлы, известно точно, и core добавит строку «приложения
    // закрыты». false — про состояние процессов ничего не известно, и мост
    // скажет об этом отдельной строкой, а не промолчит.
    bool processClosedStateKnown{};

    // Порог отбора для этого прогона. Планировщик может его менять
    // (план/профиль/тест), значение вне [0;100] приводится к границам.
    int confidenceThreshold{kSelectionThreshold};
};

// ---------------------------------------------------------------------------
// Вердикт по одному кандидату
// ---------------------------------------------------------------------------

// Что мост узнал о кандидате. Само число confidence и набор причин
// считает core::scoreCandidate; мост дописывает свои и собирает итог.
struct CandidateScore {
    // Идентификатор правила, по которому оценивали (может отсутствовать в наборе).
    std::string ruleId;

    // Уровень безопасности после оценки (FR-4). Ниже объявленного в правиле
    // не опускается: правило — решение автора, движок может только ужесточить.
    core::SafetyLevel safety{core::SafetyLevel::Review};

    // Уверенность 0–100 после поправок моста.
    int confidence{};

    // Порог, применённый к этому кандидату (из ScoringContext).
    int threshold{kSelectionThreshold};

    // Уверенность не ниже порога: элемент выбирается по умолчанию.
    bool selectableByDefault{};

    // Правило найдено в наборе. false = путь не описан ни одной строкой
    // правил, элемент не должен попасть в план сам (FR-4, §10 «путь, не
    // совпавший ни с одним известным правилом, никогда не удаляется»).
    bool ruleKnown{};

    // Объяснения моста: сначала то, о чём должен узнать человек (правило не
    // найдено, возраст неизвестен, приложения не проверялись), затем причины
    // от core::scoreCandidate.
    std::vector<std::string> reasons;

    // Причины, которые были у кандидата до оценки (сборщик: «кэш браузера
    // Edge, профиль Default, 2 145 файлов»). Строки прошлой оценки моста сюда
    // не попадают — они отсекаются по kVerdictPrefix, и applyScore пересобирает
    // список заново, не давая задвоить строки.
    std::vector<std::string> preservedReasons;

    // Одна строка вердикта для UI и отчёта: «уверенность 85 при пороге 50 —
    // выбирается по умолчанию». В плане и отчёте это строка, по которой
    // человек понимает, почему элемент выбран или пропущен (§12).
    std::string verdict;
};

// ---------------------------------------------------------------------------
// Подстановка данных
// ---------------------------------------------------------------------------

// Заполнить ScoreInput данными кандидата, его правила и прогона — ровно то,
// о чём говорит SPEC §4 FR-4, и ничего больше. Это и есть «подстановка»:
// после вызова остаётся вызвать core::scoreCandidate.
//
// rule == nullptr означает «правило в наборе не найдено»: подставляется
// безопасный Review, нулевой minAgeDays, широкий шаблон и поправка
// kUndescribedPathPenalty при оценке. Такой кандидат всё равно можно выбрать
// руками, но сам он не выбирается.
[[nodiscard]] core::ScoreInput makeScoreInput(const core::CleanupCandidate& candidate, const core::Rule* rule,
                                              const ScoringContext& context);

// Оценка кандидата целиком: подстановка + core::scoreCandidate + решения
// моста (правило найдено, неизвестный возраст, неизвестное состояние
// процессов, поправка за отсутствие правила) + текст вердикта.
[[nodiscard]] CandidateScore evaluate(const core::CleanupCandidate& candidate, const core::Rule* rule,
                                       const ScoringContext& context);

// Записать вердикт в кандидата: safety, confidence и полный список причин.
// Идемпотентно (см. инвариант 1): и повторный вызов с тем же score, и оценка
// уже оценённого кандидата дают один и тот же список.
void applyScore(const CandidateScore& score, core::CleanupCandidate& candidate);

// ---------------------------------------------------------------------------
// Массовая оценка
// ---------------------------------------------------------------------------

// Таблица «id правила → правило». core::RuleSet::byId линейный, а кандидатов
// за прогон сотни (SPEC §4 FR-3), поэтому для оценки всего скана индекс
// строится один раз, а не ищется для каждого кандидата.
using RuleLookup = std::unordered_map<std::string, const core::Rule*>;

[[nodiscard]] RuleLookup makeRuleLookup(const core::RuleSet& rules);

// Оценить весь скан и записать вердикты в кандидатов. Возвращает число
// обработанных кандидатов (равно candidates.size()): пропущенных «молча» нет
// — кандидат без оценки не попал бы в отчёт без объяснения (§12).
std::size_t scoreCandidates(std::vector<core::CleanupCandidate>& candidates, const RuleLookup& lookup,
                            const ScoringContext& context);

// То же через RuleSet: индекс строится внутри. Удобно там, где набор уже в
// руках, а таблица нужна на один вызов.
std::size_t scoreCandidates(std::vector<core::CleanupCandidate>& candidates, const core::RuleSet& rules,
                            const ScoringContext& context);

// ---------------------------------------------------------------------------
// Порог отбора
// ---------------------------------------------------------------------------

// Порог, приведённый к [0;100]. Мусорный порог из настроек не должен ронять
// оценку в ноль или делать всё «проходимым».
[[nodiscard]] int selectionThreshold(const ScoringContext& context) noexcept;

// Проходит ли кандидат порог отбора. Порог включительный: ровно 50 при пороге
// 50 проходит («не ниже порога», как в тексте FR-4).
[[nodiscard]] bool passesThreshold(int confidence, int threshold) noexcept;

// ---------------------------------------------------------------------------
// Проверки пути и шаблона (публичные — ими пользуются соседние модули движка)
// ---------------------------------------------------------------------------

// Лежит ли путь под корнем. Сравнение ТЕКСТА: регистронезависимо по ASCII,
// разделители '/' и '\' равнозначны, префикс `\\?\` и `\\?\UNC\` снимается,
// завершающие разделители игнорируются, граница проверяется по разделителю —
// «C:\Users\Ev» не влезает в «C:\Users\Evil». Кириллица сравнивается как есть:
// это осознанно (сворачивать регистр здесь — значит разойтись с
// platform::vfs_paths, где сравнение через CompareStringOrdinal).
//
// Это ЭВРИСТИКА для уверенности, а не запрет на удаление: авторитетный
// ответ на вопрос «этот путь внутри корня правила» даёт
// platform::vfs_paths::checkRuleRoot, и именно он зовётся перед операцией.
[[nodiscard]] bool isPathUnderRoot(std::string_view path, std::string_view root) noexcept;

// Широкий ли шаблон — «правило без точного имени каталога» (FR-4). Широким
// считается пустой шаблон и тот, у последнего значащего сегмента есть
// подстановка: «%USERPROFILE%\*.*», «%TEMP%\*». Точное имя каталога широким не
// считается: «...\Temp\**» — это «всё в Temp», а не «что-то под Temp».
// Завершающие сегменты «*» и «**» отбрасываются: за ними имени нет by design.
[[nodiscard]] bool isBroadLocator(std::string_view locator) noexcept;

// Кандидат внутри профиля пользователя. Пустой корень = «не доказано, что не
// пользовательский путь» → true (см. ScoringContext::userProfileRoot).
[[nodiscard]] bool isInsideUserProfile(std::string_view path, std::string_view userProfileRoot) noexcept;

// Кандидат внутри любого из системных корней. Пустой список = false (проверка
// не выполнялась), см. ScoringContext::systemRoots.
[[nodiscard]] bool isInSystemDirectory(std::string_view path, const std::vector<std::string>& systemRoots) noexcept;

}  // namespace mrproper::engine::scoring_bridge
